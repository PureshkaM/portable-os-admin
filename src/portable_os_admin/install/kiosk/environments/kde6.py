"""Режим киоска на KDE Plasma 6 (Debian 13).

Отличий от пятого поколения меньше, чем кажется: kdeglobals, kscreenlockerrc,
профили powerdevil и каталог плазмоидов остались на своих местах, и все
ограничения читаются оттуда же. Разошлись три вещи, и они собраны в
`KDE6_PATHS`:

* `kservices5` больше нет — служебные `.desktop` лежат в `kservices6`;
* модули настроек стали плагинами под Qt 6;
* кэш меню пересобирает `kbuildsycoca6`.

Поэтому здесь не копия пятого поколения, а его подкласс с другими путями:
всё, что у поколений общее, правится в одном месте, и правка не может дойти
до одного из них и не дойти до другого — ровно та ошибка, из-за которой
понадобилось разделение.

**Не проверено живым прогоном.** Написано по устройству Plasma 6 и по тому,
что Debian 13 несёт версию 6.3.6 (прочитано из образа). До прогона считать
непроверенным — под KDE 5 половина ограничений оказалась не тем, чем
выглядела.
"""
from __future__ import annotations

from .kde import KDE6_PATHS, Kde5Environment


class Kde6Environment(Kde5Environment):
    paths = KDE6_PATHS
