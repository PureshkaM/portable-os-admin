"""Удалённый отзыв носителя: проверка при каждой загрузке.

Задача, ради которой это существует: уволившийся сотрудник с невозвращённым
носителем и уже зарегистрированной машиной сохраняет доступ, и отменить это
нечем. Привязка к машинам закрывает только чужие машины, но не бывшего своего.

Механизм. При каждой загрузке носитель спрашивает у общедоступного ресурса своё
состояние по идентификатору и, получив «отозван», уничтожает себя.

**Уничтожает себя, а не только заголовок.** Сперва здесь стоял один `luksErase`
системного тома: мастер-ключ исчезает, данные становятся шумом. Живая проверка
14.09.2026 показала, чего этого не покрывает, и требование было поставлено
прямо -- после отзыва носитель непригоден безвозвратно, дальше дорога к
администратору на переустановку. По этой мерке одного `luksErase` мало:

* тома журналов и обмена -- отдельные контейнеры со своими ключами, их
  `luksErase` системного тома не касается вовсе;
* заголовок остаётся читаемым, а у того, кто носитель не вернул, могла заранее
  осесть его копия (`luksHeaderBackup` доступен всякому с правами root на своей
  же машине). Копия плюс известная пользователю фраза -- это восстановленный
  доступ, и снять её мы уже не можем: она вне носителя. Отсюда затирание самих
  данных -- единственное, что копию заголовка обесценивает;
* носитель остаётся загрузочным, то есть выглядит «сломавшимся», а не
  отозванным.

Затирание сплошняком на USB идёт часами и прерывается выдёргиванием флешки,
поэтому проход двойной: сплошь по началу тома, где метаданные файловой системы
и начало образа, и дальше по мегабайту через каждые 32 -- образ с дырами такого
шага не читается ничем, а времени уходит минуты. Порядок шагов -- строго от
главного к второстепенному: прерывание на любом из них уже не оставляет доступа
к данным.

Решения, принятые при разборе 11.09.2026, и причины -- в `docs/DELIVERY.md`.
Здесь только то, что вытекает из них для кода:

**Ресурс общедоступный, а не внутренний.** Проверка обязана срабатывать
раньше, чем носитель дотянется до внутренней сети: ресурс во внутреннем контуре
означал бы, что отозванный носитель сперва попадает внутрь периметра, а уже
потом узнаёт, что он отозван.

**Ответ подписан ключом администратора, а не доверием к удостоверяющим
центрам.** Тот же Ed25519, на котором стоит обмен конфигурациями. Открытая
часть кладётся на носитель при записи; закрытая не покидает контейнера.
Проверка идёт `openssl`, который есть в обоих семействах, а не питоном:
скрипт работает до входа пользователя и не должен зависеть от интерпретатора.

**Запрос несёт случайное число, и оно же подписано в ответе.** Это и есть
защита от повтора: старый ответ «носитель в порядке», снятый месяц назад,
подсунуть нельзя -- в нём другое число. Часов и счётчиков на носителе для
этого не нужно, а именно они на переносной системе ненадёжны.

**Нет сети -- работаем дальше.** Решение пользователя: носитель, никогда не
выходящий в интернет, до рабочего места всё равно не доходит. Срока доверия
(«не отметился N дней -- блокируйся») нет намеренно.
"""
from __future__ import annotations

from ..config.schema import InstallConfig

SCRIPT_PATH = "usr/local/sbin/poa-revocation"
SERVICE_PATH = "etc/systemd/system/poa-revocation.service"
SERVICE_NAME = "poa-revocation.service"

#: Открытый ключ администратора в формате PEM. Кладётся при записи носителя
#: рядом со служебным ключом; закрытая часть остаётся в контейнере.
PUBLIC_KEY_PATH = "etc/poa/revocation.pub"

#: Журнал -- на томе журналов, как и у автообновления: администратор читает его
#: своим ключом, не зная парольной фразы пользователя. Носитель, который
#: отметился и жив, виден по этим строкам -- это и есть учёт парка.
LOG_PATH = "/var/log/poa-revocation.log"


def is_enabled(config: InstallConfig) -> bool:
    settings = getattr(config, "revocation", None)
    return bool(settings and settings.enabled and settings.url.strip())


def revocation_script(
    config: InstallConfig,
    media_id: str,
    luks_uuid: str,
    logs_luks_uuid: str = "",
    exchange_luks_uuid: str = "",
    esp_uuid: str = "",
    boot_uuid: str = "",
) -> str:
    """Скрипт проверки. Идентификатор, адрес и UUID томов вписаны в текст.

    UUID служебных томов и загрузочных разделов приходят необязательными: в
    старых раскладках их может не быть, и отсутствие означает «этот шаг
    пропустить», а не «ничего не уничтожать». Системный том -- обязателен,
    без него скрипт не собирается вовсе.

    То, что никогда не попадает в командную строку, нельзя закавычить
    неправильно -- тем же приёмом собран скрипт режима киоска.

    **Том ищется по UUID заголовка LUKS, а не по пути раздела**, и это не
    педантизм. До 14.09.2026 в скрипт вписывался путь, каким раздел назывался
    на машине администратора -- `/dev/loop1p3`, `/dev/sdb3`. На загруженном
    носителе такого устройства нет: живая проверка отзыва показала в журнале
    носителя «Device /dev/loop1p3 does not exist or access denied» и
    «ОШИБКА: заголовок уничтожить не удалось». Вся цепочка -- служба, запрос,
    подпись, состояние `revoked` -- отработала, и не сработал последний шаг.

    Хуже, чем «не сработал»: на чужой машине путь `/dev/sdb3` вполне может
    существовать и принадлежать постороннему диску, а `luksErase` необратим.
    Поэтому устройство ищется по UUID и **перед уничтожением сверяется ещё
    раз**: стирается только тот том, чей `luksUUID` совпал.

    Уничтожается заголовок раздела, а не отображения: `luksErase` работает с
    диском, и открытый в данный момент том этому не мешает. Сеанс доживёт до
    перезагрузки, а следующей загрузки не будет -- ни с паролем, ни с кодом
    восстановления.

    Порядок шагов -- не оформительский: питание могут выдернуть на любом из
    них, поэтому сперва идёт то, после чего доступа к данным нет (ключи
    системного тома и тома обмена), потом затирание данных, и только затем
    второстепенное -- загрузочная часть и разметка. Том журналов уничтожается
    предпоследним, потому что до этого в него пишется каждый шаг; дальше журнал
    переезжает в память. Почему одних ключей мало -- в шапке модуля.
    """
    settings = config.revocation
    url = settings.url.strip().rstrip("/")
    timeout = max(1, int(settings.timeout_seconds or 10))

    return f"""#!/bin/sh
# generated by portable-os-admin
# Проверка отзыва носителя при загрузке.
#
# Ответ ресурса проверяется подписью администратора. Без подписи или с чужой
# подписью ответ не значит ничего: иначе отозвать носитель мог бы всякий, кто
# сумел подменить ответ по дороге, -- а уничтожение необратимо.

LOG={LOG_PATH}
MEDIA_ID={media_id}
URL={url}
KEY=/{PUBLIC_KEY_PATH}
LUKS_UUID={luks_uuid}
LOGS_UUID={logs_luks_uuid}
EXCHANGE_UUID={exchange_luks_uuid}
ESP_UUID={esp_uuid}
BOOT_UUID={boot_uuid}
TIMEOUT={timeout}

log() {{
    echo "$(date '+%Y-%m-%d %H:%M:%S') $*" >> "$LOG"
}}

say() {{
    # Сообщение человеку: сеанс ещё не начался, поэтому консоль, а не окно.
    echo "$1" > /dev/console 2>/dev/null || echo "$1"
}}

log "=== проверка отзыва ==="

if [ ! -f "$KEY" ]; then
    log "нет открытого ключа администратора, проверка невозможна"
    exit 0
fi

# Инструменты названы поимённо, потому что их отсутствие -- самый тихий из
# возможных отказов: без curl или openssl проверка не сработает ни разу, а
# носитель будет выглядеть исправным. Строка в журнале превращает это из
# «молча не работает» в «сказано, чего не хватает».
for tool in curl openssl base64 od; do
    command -v "$tool" >/dev/null 2>&1 || {{
        log "нет $tool -- проверка отзыва невозможна"
        exit 0
    }}
done

# Без сети проверять нечем, и это не ошибка: см. решение «нет сети -- работаем
# дальше». Носитель, никогда не выходящий в интернет, до рабочего места и так
# не доходит.
if ! ip route show default 2>/dev/null | grep -q .; then
    log "сети нет, проверка пропущена"
    exit 0
fi

# Случайное число запроса. Ответ подписывается вместе с ним, поэтому вчерашний
# ответ сегодня не подойдёт.
NONCE=$(head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \\n')
if [ -z "$NONCE" ]; then
    log "не удалось получить случайное число, проверка пропущена"
    exit 0
fi

WORK=$(mktemp -d) || exit 0
trap 'rm -rf "$WORK"' EXIT INT TERM

if ! curl --silent --show-error --fail --max-time "$TIMEOUT" \\
        --output "$WORK/answer" \\
        "$URL/state?media=$MEDIA_ID&nonce=$NONCE" 2>>"$LOG"; then
    log "ресурс недоступен, проверка пропущена"
    exit 0
fi

# Ответ: две строки. Первая -- сообщение, вторая -- подпись в base64.
# Разделение строками, а не разбором JSON: разбирать структуру в shell до
# входа пользователя -- лишний способ ошибиться, а подписывается ровно первая
# строка целиком.
MESSAGE=$(sed -n '1p' "$WORK/answer")
SIGNATURE=$(sed -n '2p' "$WORK/answer")
if [ -z "$MESSAGE" ] || [ -z "$SIGNATURE" ]; then
    log "ответ ресурса непонятен, проверка пропущена"
    exit 0
fi

printf '%s' "$MESSAGE" > "$WORK/message"
printf '%s' "$SIGNATURE" | base64 -d > "$WORK/signature" 2>/dev/null || {{
    log "подпись не разбирается, ответ отброшен"
    exit 0
}}

if ! openssl pkeyutl -verify -pubin -inkey "$KEY" -rawin \\
        -in "$WORK/message" -sigfile "$WORK/signature" >/dev/null 2>&1; then
    log "ПОДПИСЬ НЕ СХОДИТСЯ, ответ отброшен"
    exit 0
fi

# Подпись сошлась -- теперь проверяется, что подписан ответ именно на наш
# запрос. Без этого подошёл бы подписанный ответ про другой носитель или
# снятый месяц назад.
case "$MESSAGE" in
    "poa-state $MEDIA_ID $NONCE "*) ;;
    *)
        log "ответ подписан, но не на наш запрос, отброшен"
        exit 0
        ;;
esac

STATE=${{MESSAGE##* }}
log "состояние: $STATE"

if [ "$STATE" != "revoked" ]; then
    exit 0
fi

# --- Дальше необратимое ----------------------------------------------------
#
# Порядок строго от главного к второстепенному: питание могут выдернуть на
# любом шаге, и на каждом промежуточном срезе доступа к данным уже не должно
# быть. Сперва ключи томов, затем сами данные, затем загрузочная часть, и лишь
# в самом конце -- разметка.

FAILED=0

# Путь раздела с машины администратора на носителе не значит ничего, поэтому
# том ищется по UUID заголовка. А перед необратимым UUID сверяется ещё раз: на
# чужой машине путь вроде /dev/sdb3 существует сплошь и рядом и принадлежит
# постороннему диску.
find_volume() {{
    _uuid=$1
    [ -n "$_uuid" ] || return 1
    if [ -e "/dev/disk/by-uuid/$_uuid" ]; then
        readlink -f "/dev/disk/by-uuid/$_uuid"
        return 0
    fi
    if command -v blkid >/dev/null 2>&1; then
        _found=$(blkid -t UUID="$_uuid" -o device 2>/dev/null | head -1)
        if [ -n "$_found" ]; then
            echo "$_found"
            return 0
        fi
    fi
    return 1
}}

# Затирание начала устройства. Заголовок LUKS2 -- это первые 16 МиБ (две копии
# заголовка и слоты ключей); берём с запасом.
wipe_head() {{
    dd if=/dev/zero of="$1" bs=1M count="$2" conv=fsync >/dev/null 2>&1
}}

# Результат кладётся в VOLUME_DEV, а не печатается: подстановка $(...) увела бы
# функцию в подоболочку, и счёт ошибок в FAILED пропал бы вместе с ней.
destroy_luks() {{
    VOLUME_DEV=""
    _uuid=$1
    _name=$2
    if [ -z "$_uuid" ]; then
        log "$_name: UUID не записан в скрипт, шаг пропущен"
        return 1
    fi
    _dev=$(find_volume "$_uuid")
    if [ -z "$_dev" ]; then
        log "ОШИБКА: $_name -- том с UUID $_uuid не найден"
        FAILED=1
        return 1
    fi
    _found=$(cryptsetup luksUUID "$_dev" 2>/dev/null)
    if [ "$_found" != "$_uuid" ]; then
        log "ОШИБКА: $_name -- $_dev не тот том (UUID $_found), не трогаю"
        FAILED=1
        return 1
    fi
    if cryptsetup luksErase "$_dev" --batch-mode >>"$LOG" 2>&1; then
        log "$_name: слоты ключей уничтожены ($_dev)"
    else
        log "ОШИБКА: $_name -- luksErase не отработал ($_dev)"
        FAILED=1
    fi
    # Поверх -- нули: luksErase оставляет заголовок читаемым, а он рассказывает,
    # что на носителе было и чем зашифровано.
    if wipe_head "$_dev" 32; then
        log "$_name: заголовок затёрт ($_dev)"
    else
        log "ОШИБКА: $_name -- заголовок затереть не удалось ($_dev)"
        FAILED=1
    fi
    VOLUME_DEV=$_dev
    return 0
}}

# Затирание самих данных. Нужно оно против одного сценария: у того, кто носитель
# не вернул, могла заранее осесть копия заголовка, а фразу он знает и так. Копия
# лежит вне носителя, отобрать её нельзя -- значит, обесценить её может только
# то, что копия открывает.
wipe_data() {{
    _dev=$1
    _total=0
    if command -v blockdev >/dev/null 2>&1; then
        _bytes=$(blockdev --getsize64 "$_dev" 2>/dev/null)
        [ -n "$_bytes" ] && _total=$(( _bytes / 1048576 ))
    fi
    log "затираю первый гигабайт тома $_dev"
    dd if=/dev/zero of="$_dev" bs=1M count=1024 conv=fsync >/dev/null 2>&1
    if [ "$_total" -le 1024 ]; then
        log "том затёрт целиком"
        return 0
    fi
    # Дальше -- по мегабайту через каждые 32. Сплошной проход по флешке идёт
    # часами и почти наверняка будет прерван выдёргиванием; проход с шагом даёт
    # для любого читателя тот же результат -- ни файловая система, ни образ с
    # дырами такого шага не собираются, -- но укладывается в минуты.
    log "затираю остальное с шагом 32 МиБ (всего $_total МиБ)"
    _at=1024
    while [ "$_at" -lt "$_total" ]; do
        dd if=/dev/zero of="$_dev" bs=1M count=1 seek="$_at" conv=fsync >/dev/null 2>&1 || break
        _at=$(( _at + 32 ))
    done
    log "данные затёрты до отметки $_at МиБ"
}}

wipe_boot() {{
    _uuid=$1
    _name=$2
    if [ -z "$_uuid" ]; then
        log "$_name: UUID не записан в скрипт, шаг пропущен"
        return 0
    fi
    _dev=$(find_volume "$_uuid")
    if [ -z "$_dev" ]; then
        log "$_name: раздел не найден, шаг пропущен"
        return 0
    fi
    umount "$_dev" >/dev/null 2>&1
    if wipe_head "$_dev" 16; then
        log "$_name: загрузчик затёрт ($_dev)"
    else
        log "ОШИБКА: $_name -- затереть не удалось ($_dev)"
        FAILED=1
    fi
}}

log "НОСИТЕЛЬ ОТОЗВАН, уничтожаю"
say ""
say "Носитель отозван администратором. Доступ к данным прекращён."
say "Идёт уничтожение носителя, не выключайте машину."

# 1. Системный том -- главное. Уничтожается заголовок раздела, а не отображения:
#    luksErase работает с диском, и открытый сейчас том этому не мешает. Сеанс
#    доживёт до перезагрузки, а следующей загрузки не будет -- ни с фразой, ни с
#    кодом восстановления.
destroy_luks "$LUKS_UUID" "системный том"
SYSTEM_DEV=$VOLUME_DEV

# 2. Том обмена -- отдельный контейнер со своим ключом, первым шагом он не
#    затронут вовсе.
destroy_luks "$EXCHANGE_UUID" "том обмена"

# 3. Данные системного тома.
if [ -n "$SYSTEM_DEV" ]; then
    wipe_data "$SYSTEM_DEV"
fi

# 4. Загрузочная часть: отозванный носитель не должен грузиться вообще, иначе он
#    выглядит сломавшимся, а не отозванным.
wipe_boot "$BOOT_UUID" "раздел /boot"
wipe_boot "$ESP_UUID" "раздел ESP"

# 5. Том журналов -- последним из томов: до этой строки каждый шаг писался
#    именно в него. Дальше писать некуда, и журнал переезжает в память: прочесть
#    его можно будет только до выключения, но к этому моменту всё уже сделано.
if [ -n "$LOGS_UUID" ]; then
    log "том журналов уничтожается следующим, дальше строки только в памяти"
    sync
    LOG=/run/poa-revocation.log
    destroy_luks "$LOGS_UUID" "том журналов"
fi

# 6. Разметка -- в самом конце и только от уже проверенного раздела: носитель
#    должен выглядеть чистым, но ошибиться здесь диском страшнее, чем пропустить
#    шаг. Затирается и начало, и хвост -- в хвосте лежит запасная копия GPT, из
#    которой разметка иначе восстанавливается одной командой.
if [ -n "$SYSTEM_DEV" ] && command -v lsblk >/dev/null 2>&1; then
    PARENT=$(lsblk -no pkname "$SYSTEM_DEV" 2>/dev/null | head -1)
    if [ -n "$PARENT" ] && [ -b "/dev/$PARENT" ]; then
        dd if=/dev/zero of="/dev/$PARENT" bs=1M count=4 conv=fsync >/dev/null 2>&1
        DISK_MB=0
        if command -v blockdev >/dev/null 2>&1; then
            DISK_BYTES=$(blockdev --getsize64 "/dev/$PARENT" 2>/dev/null)
            [ -n "$DISK_BYTES" ] && DISK_MB=$(( DISK_BYTES / 1048576 ))
        fi
        if [ "$DISK_MB" -gt 8 ]; then
            dd if=/dev/zero of="/dev/$PARENT" bs=1M count=4 seek=$(( DISK_MB - 4 )) \\
                conv=fsync >/dev/null 2>&1
        fi
        log "разметка затёрта (/dev/$PARENT)"
    else
        log "родительский диск не определён, разметка оставлена как есть"
    fi
fi

sync

if [ "$FAILED" -eq 0 ]; then
    log "=== носитель уничтожен ==="
    say ""
    say "Носитель уничтожен. Для восстановления обратитесь к администратору."
else
    log "=== уничтожение прошло не полностью, см. строки ОШИБКА выше ==="
    say ""
    say "Отзыв доведён не до конца. Обратитесь к администратору."
fi

sleep 5
poweroff -f 2>/dev/null || echo o > /proc/sysrq-trigger
exit 0
"""


def service_unit() -> str:
    """Служба, запускающая проверку один раз за загрузку.

    После сети и до входа пользователя не выстроить: сеанс поднимается
    параллельно, и ждать проверки означало бы задерживать загрузку у всех ради
    случая, который бывает раз в жизни носителя. Отозванный носитель успеет
    показать рабочий стол на несколько секунд -- и это не дыра: данных на нём
    нет, они на рабочем компьютере внутри компании, а заголовок к этому моменту
    уже уничтожен.
    """
    return f"""# generated by portable-os-admin
[Unit]
Description=Проверка отзыва переносного носителя
After=network-online.target
Wants=network-online.target
# Журнал службы лежит в /var/log, а это отдельный зашифрованный том носителя.
# Без этой строки служба успевает написать раньше, чем том смонтирован, и
# строки ложатся на корень -- под точку монтирования, где администратор их уже
# не увидит: раздел «Журналы» читает том. Найдено живой загрузкой 13.09.2026.
RequiresMountsFor=/var/log

[Service]
Type=oneshot
ExecStart=/{SCRIPT_PATH}
# Предела нет намеренно. Сетевые шаги ограничены своим `--max-time`, а вот
# уничтожение отозванного носителя длится столько, сколько длится затирание
# тома на USB, -- и предел в пять минут означал бы `SIGTERM` ровно посреди
# него: часть носителя затёрта, часть цела, и какая именно -- как повезёт.
TimeoutStartSec=infinity

[Install]
WantedBy=multi-user.target
"""


def config_files(
    config: InstallConfig,
    media_id: str = "",
    luks_uuid: str = "",
    logs_luks_uuid: str = "",
    exchange_luks_uuid: str = "",
    esp_uuid: str = "",
    boot_uuid: str = "",
) -> dict[str, tuple[str, int | None]]:
    """Файлы носителя. Пусто, пока отзыв не включён или носитель неизвестен.

    `media_id` и UUID приходят от установщика: они разные у каждого носителя,
    поэтому эти файлы пишутся при записи, а не попадают в образ дистрибутива --
    иначе все носители спрашивали бы ресурс об одном и том же идентификаторе.
    """
    if not is_enabled(config) or not media_id or not luks_uuid:
        return {}
    script = revocation_script(
        config,
        media_id,
        luks_uuid,
        logs_luks_uuid=logs_luks_uuid,
        exchange_luks_uuid=exchange_luks_uuid,
        esp_uuid=esp_uuid,
        boot_uuid=boot_uuid,
    )
    return {
        SCRIPT_PATH: (script, 0o755),
        SERVICE_PATH: (service_unit(), 0o644),
    }


