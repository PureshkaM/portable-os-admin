"""Unattended updates on the finished medium, run at every boot.

A fleet of portable systems is handed out and not easily collected back, so
each medium has to patch itself. This installs a small script and a systemd
service that upgrades packages from the repository the configuration names.

Three decisions worth stating, because each is the difference between a
feature and a nuisance:

**It never blocks the boot.** The unit is wanted by multi-user.target and
ordered after the network is up, and the script sleeps before it starts work.
An upgrade competing with the desktop session for the same slow USB device
would otherwise turn the first minutes after login into a crawl, and an
upgrade that ran *before* the session would look to the user like a medium
that takes ten minutes to start.

**It writes where the administrator can read it.** The log goes to
/var/log, which on this project's media is a separate LUKS volume the
administrator opens with a service key kept in their own container, without
the user's LUKS passphrase (see admin/logs.py). Until 11.09.2026 this said
"a separate unencrypted volume the administrator can open with their own
key", which contradicted both itself and the code. So "did that stick ever
take the update?" is answerable by plugging it in, which for a fleet is the
whole question.

**It refuses to run rather than half-run.** No repository configured, no
network, another package manager already running -- each is a clean exit with
a line in the log, not a partial upgrade. A medium interrupted mid-upgrade is
the one failure mode here that can leave a system that does not boot.
"""
from __future__ import annotations

from ..config.schema import InstallConfig

SCRIPT_PATH = "usr/local/sbin/poa-update"
SERVICE_PATH = "etc/systemd/system/poa-update.service"
SERVICE_NAME = "poa-update.service"
#: On the log volume, so it survives on the medium and is readable by the
#: administrator without the user's passphrase.
LOG_PATH = "/var/log/poa-update.log"


def is_enabled(config: InstallConfig) -> bool:
    return bool(getattr(config, "auto_update", None) and config.auto_update.enabled)


def update_script(config: InstallConfig, backend) -> str:
    """The script itself, with this family's package commands baked in.

    `set -e` is deliberately *not* used: every failure here has a specific
    message worth writing to the log, and an unattended job that dies without
    saying why is indistinguishable from one that never ran.
    """
    settings = config.auto_update
    delay_seconds = max(0, int(settings.delay_minutes or 0)) * 60
    refresh = " ".join(backend.update_refresh_command())
    upgrade = " ".join(backend.update_upgrade_command(include_kernel=settings.include_kernel))
    holds = backend.update_hold_commands(include_kernel=settings.include_kernel)
    hold_block = "\n".join(holds)

    return f"""#!/bin/sh
# generated by portable-os-admin
# Автоматическое обновление переносной системы при загрузке.
#
# Журнал ведётся на отдельном разделе журналов: администратор может прочитать
# его своим ключом, не зная парольной фразы пользователя.

LOG={LOG_PATH}

log() {{
    echo "$(date '+%Y-%m-%d %H:%M:%S') $*" >> "$LOG"
}}

log "=== запуск автообновления ==="

# Пауза после загрузки: обновление идёт на том же медленном носителе, с
# которого стартует рабочий стол, и без задержки первые минуты сеанса
# превращаются в ожидание.
sleep {delay_seconds}

# Без сети обновляться неоткуда. Проверяется маршрут по умолчанию, а не
# доступность конкретного узла: в изолированном контуре пинговать наружу
# бессмысленно, а репозиторий может стоять в этой же сети.
if ! ip route show default 2>/dev/null | grep -q .; then
    log "сети нет, обновление пропущено"
    exit 0
fi

{hold_block}

log "обновление списка пакетов"
if ! {refresh} >> "$LOG" 2>&1; then
    log "ОШИБКА: не удалось обновить список пакетов (репозиторий недоступен?)"
    exit 1
fi

log "установка обновлений"
if {upgrade} >> "$LOG" 2>&1; then
    log "обновление завершено успешно"
else
    log "ОШИБКА: обновление завершилось с ошибкой"
    exit 1
fi

# Размер журнала ограничивается здесь, а не через logrotate: раздел журналов
# невелик, а носитель может годами не попадать к администратору.
if [ -f "$LOG" ] && [ "$(wc -c < "$LOG")" -gt 5242880 ]; then
    tail -c 1048576 "$LOG" > "$LOG.tmp" && mv "$LOG.tmp" "$LOG"
    log "журнал обновлений усечён"
fi

exit 0
"""


def service_unit(config: InstallConfig) -> str:
    """systemd unit running the script once per boot.

    `Type=oneshot` with no `Before=` on anything: the unit is started as part
    of multi-user.target and nothing waits for it, so the desktop session comes
    up while this is still working.

    TimeoutStartSec is generous rather than absent -- an upgrade of a few
    hundred megabytes onto USB flash is slow, and the default would kill it
    partway, which is the one outcome that can leave a medium unbootable.
    """
    return f"""# generated by portable-os-admin
[Unit]
Description=Автоматическое обновление переносной системы
# Обновляться можно только когда сеть уже поднята.
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/{SCRIPT_PATH}
# Ничего не ждёт завершения этой службы, поэтому долгий запуск не задерживает
# ни загрузку, ни вход пользователя.
TimeoutStartSec=3h
# Обновление не должно мешать работе: у него низший приоритет и по процессору,
# и по вводу-выводу, потому что диск здесь -- та же флешка, с которой работает
# пользователь.
Nice=19
IOSchedulingClass=idle

[Install]
WantedBy=multi-user.target
"""


def config_files(config: InstallConfig, backend) -> dict[str, tuple[str, int | None]]:
    if not is_enabled(config):
        return {}
    return {
        SCRIPT_PATH: (update_script(config, backend), 0o755),
        SERVICE_PATH: (service_unit(config), 0o644),
    }


def chroot_commands(mount_root: str, config: InstallConfig, backend) -> list[list[str]]:
    if not is_enabled(config):
        return []
    return [backend.systemctl_enable(mount_root, SERVICE_NAME)]
