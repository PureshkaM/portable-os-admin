MEDIA_LABEL_PREFIX = "POA_"


def hidden_volumes_udev_rules() -> str:
    """Служебные разделы носителя не показываются рабочим столом.

    Прогон 04.09.2026: в меню Plasma, во вкладке «Places» → «Removable
    Devices», лежал раздел `POA_EXCHANGE` -- то есть пользователю киоска
    показывали устройство, на котором он работает.

    Закрывается там, где рабочий стол берёт список, а не в каждой оболочке
    по отдельности. И KDE, и MATE спрашивают Solid/udisks2, а Solid считает
    том незначащим по свойству `HintIgnore` (`udisksstoragevolume.cpp:82` и
    `udisksstorageaccess.cpp:276` в kf6-solid 6.13) -- оба, потому что
    предикат мест KDE проверяет и том, и доступ к нему:

        [[[[ StorageVolume.ignored == false AND [ StorageVolume.usage ==
        'FileSystem' OR ... ]] ... ] OR StorageAccess.ignored == false ]

    (прочитано из самой libKF6KIOFileWidgets, а не из документации).
    `HintIgnore` udisks2 берёт из udev-переменной `UDISKS_IGNORE`, и это
    единственное место, где мы можем на него повлиять.

    **Проверено на стенде** 07.09.2026, без сеанса Plasma: том с меткой
    `POA_TESTLBL` показывал `HintIgnore: false`; после этого правила и
    `udevadm trigger` -- `HintIgnore: true`.

    Правило написано по метке, а не по устройству: имена (`/dev/sdb5`)
    зависят от того, куда носитель воткнули, а метка ставится нами при
    разметке и едет вместе с разделом.
    """
    return (
        "# generated by portable-os-admin\n"
        "# Служебные разделы носителя не показываются рабочим столом: udisks2\n"
        "# ставит по этой переменной HintIgnore, а Solid по нему считает том\n"
        "# незначащим -- и он исчезает из мест KDE и из списков съёмных\n"
        "# устройств. Ничего не отключает и не запрещает: раздел продолжает\n"
        "# монтироваться по fstab как прежде.\n"
        f'SUBSYSTEM=="block", ENV{{ID_FS_LABEL}}=="{MEDIA_LABEL_PREFIX}*", '
        'ENV{UDISKS_IGNORE}="1"\n'
    )


#: Куда служба кладёт правило: /run живёт одну загрузку, и это ровно тот срок,
#: на который запрет и нужен.
UDEV_RUNTIME_RULES_PATH = "/run/udev/rules.d/99-poa-kiosk-storage.rules"
#: Служба, включающая запрет после того, как система поднялась.
USB_LOCKDOWN_UNIT_PATH = "etc/systemd/system/poa-usb-lockdown.service"


def usb_lockdown_unit(config: InstallConfig) -> str:
    """Служба, включающая запрет на чужие накопители после загрузки.

    Существует из-за coldplug: правило, лежащее в `/etc`, применяется и к
    носителю, с которого система загрузилась, и он отключает сам себя. Здесь
    же правило появляется, когда загрузка закончена, и действует на то, что
    подключат потом.

    `After=multi-user.target` и `RemainAfterExit=yes`: служба разово пишет
    файл и перечитывает правила, а состояние «запрет включён» держится до
    выключения -- перезапускать нечего.
    """
    if config.kiosk.allow_removable_media:
        return ""
    rules = udev_storage_rules(config).replace("'", "'\\''")
    return (
        "# generated by portable-os-admin\n"
        "[Unit]\n"
        "Description=Запрет на подключение чужих USB-накопителей\n"
        "# После того как система поднялась: правило, действующее раньше,\n"
        "# срабатывает на coldplug и отключает загрузочный носитель.\n"
        "After=multi-user.target\n"
        "\n"
        "[Service]\n"
        "Type=oneshot\n"
        "RemainAfterExit=yes\n"
        "ExecStart=/bin/sh -c 'mkdir -p /run/udev/rules.d && "
        f"printf %s '\\''{rules}'\\'' > {UDEV_RUNTIME_RULES_PATH} && "
        "udevadm control --reload'\n"
        "\n"
        "[Install]\n"
        "WantedBy=multi-user.target\n"
    )
