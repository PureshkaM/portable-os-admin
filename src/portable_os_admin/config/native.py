"""Rendering the configuration in each distribution's own automated-install format.

The point is validation. This project's configuration is its own document, so
checking it against rules invented here proves only that it agrees with itself.
Both target families ship an official validator for their own automated-install
file -- `ksvalidator` from pykickstart for the RHEL family, and
`debconf-set-selections --checkonly` from debconf for Debian -- so the
configuration is rendered into that format and handed to the distribution's own
tool. That is the "внешнее средство проверки конфигурации" the project's
specification asks for, and it is a real external standard rather than a
private opinion.

What each tool actually proves is different, and worth being precise about:

  * ksvalidator parses the whole kickstart file: it rejects removed and
    deprecated commands, missing required options, mutually exclusive options
    and some classes of partitioning error.
  * debconf-set-selections --checkonly validates the *format* of a preseed
    file -- that every line names an owner, a question, a type and a value.
    It says nothing about whether the values make sense.

Neither replaces this project's own structural checks, which know things
neither tool does (that /boot must be outside the LUKS volume, which key sizes
a given cipher accepts). Validation runs both.

The rendered files are also useful in themselves: they are what an
administrator would hand to the distribution's own installer.
"""
from __future__ import annotations

from .schema import InstallConfig

#: Which native format each target family uses.
NATIVE_FORMAT = {"debian": "preseed", "redos": "kickstart"}


def render(config: InstallConfig) -> tuple[str, str]:
    """Returns (format, text) for the configuration's target family."""
    fmt = NATIVE_FORMAT.get(config.target_os, "preseed")
    return fmt, (to_kickstart(config) if fmt == "kickstart" else to_preseed(config))


def to_kickstart(config: InstallConfig) -> str:
    """A kickstart file describing the same install this program performs.

    Not every field maps: this program partitions the medium itself and unlocks
    it from an initramfs, so the kickstart says `autopart --encrypted` rather
    than reproducing the exact five-partition layout. What it does carry is
    every value a person actually authored -- account, groups, packages,
    services -- which is what validation is for.
    """
    disk = config.disk
    account = config.account
    loc = config.localisation
    lines = [
        "# Generated by portable-os-admin for validation with ksvalidator.",
        "# It describes the same installation this program performs.",
        "text",
        f"keyboard --vckeymap={loc.keymap}",
        f"lang {loc.locale}",
        f"timezone {loc.timezone}" + (" --utc" if loc.hardware_clock_utc else ""),
        f"network --hostname={config.hostname}",
        # The account has no usable password by design: the LUKS passphrase is
        # the single front-door secret.
        "rootpw --lock",
        "firstboot --disable",
        "clearpart --all --initlabel",
        f"part /boot/efi --fstype=efi --size={disk.esp_partition_mb}",
        f"part /boot --fstype=ext4 --size={disk.boot_partition_mb}",
        f"part /var/log --fstype=ext4 --size={disk.log_partition_mb}",
        "part / --fstype=ext4 --grow --encrypted --luks-version=luks2 "
        f"--cipher={config.luks.cipher} --pbkdf={config.luks.kdf}",
        "bootloader --location=mbr",
    ]

    groups = f" --groups={_sudo_group(config)}" if account.sudo else ""
    fullname = f' --gecos="{account.full_name}"' if account.full_name else ""
    lines.append(f"user --name={account.username} --shell={account.shell}{groups}{fullname} --lock")

    if config.remote_access.enabled:
        lines.append("services --enabled=sshd")
        lines.append(f"firewall --enabled --port={config.remote_access.port}:tcp")

    lines.append("")
    lines.append("%packages")
    lines.append("@core")
    lines += list(config.packages)
    if config.remote_access.enabled:
        lines.append("openssh-server")
    lines.append("%end")
    lines.append("")
    return "\n".join(lines) + "\n"


def to_preseed(config: InstallConfig) -> str:
    """A preseed file describing the same install this program performs.

    Every line is `owner question type value`, which is the shape
    `debconf-set-selections --checkonly` verifies.
    """
    account = config.account
    disk = config.disk
    lines = [
        "# Generated by portable-os-admin for validation with",
        "# debconf-set-selections --checkonly. It describes the same",
        "# installation this program performs.",
        f"d-i debian-installer/locale string {config.localisation.locale}",
        f"d-i keyboard-configuration/xkb-keymap select {config.localisation.keymap}",
        "d-i clock-setup/utc boolean "
        + ("true" if config.localisation.hardware_clock_utc else "false"),
        f"d-i time/zone string {config.localisation.timezone}",
        f"d-i netcfg/get_hostname string {config.hostname}",
        # Root login is disabled and the account's password is locked: the LUKS
        # passphrase is the only secret at the front door.
        "d-i passwd/root-login boolean false",
        f"d-i passwd/username string {account.username}",
        f"d-i passwd/user-fullname string {account.full_name or account.username}",
        "d-i partman-auto/method string crypto",
        f"d-i partman-auto/expert_recipe string poa :: "
        f"{disk.esp_partition_mb} {disk.esp_partition_mb} {disk.esp_partition_mb} fat32 "
        f". {disk.boot_partition_mb} {disk.boot_partition_mb} {disk.boot_partition_mb} ext4 "
        f". {disk.log_partition_mb} {disk.log_partition_mb} {disk.log_partition_mb} ext4 "
        ". 4096 10000 -1 ext4 .",
        "d-i partman/confirm boolean true",
        "d-i partman/confirm_nooverwrite boolean true",
    ]

    selected = list(config.packages)
    if config.remote_access.enabled:
        selected.append("openssh-server")
    if selected:
        lines.append(f"d-i pkgsel/include string {' '.join(selected)}")
    lines.append("d-i pkgsel/upgrade select none")
    lines.append("d-i finish-install/reboot_in_progress note")
    return "\n".join(lines) + "\n"


def _sudo_group(config: InstallConfig) -> str:
    """The group that grants administrative rights on the target family.

    Debian grants it through `sudo`, the RHEL family through `wheel`. Taken
    from the backend so this file and the installer cannot drift apart.
    """
    from ..install.backends import get_backend

    return get_backend(config.target_os).sudo_group
