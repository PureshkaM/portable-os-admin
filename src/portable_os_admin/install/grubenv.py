"""Блок переменных GRUB (`grubenv`) -- чтение и запись без `grub-editenv`.

Ручное обновление носителя (Э9) пишет `poa_try` на машине администратора, а
там `grub-editenv` может не оказаться (macOS, Windows, урезанный Linux).
Формат простой и неизменный с GRUB 1.98:

* ровно 1024 байта;
* первая строка `# GRUB Environment Block`;
* дальше строки `имя=значение`;
* остаток добит символами `#`.

Пишется **на месте**, теми же 1024 байтами, как это делает сам
`grub-editenv`: GRUB `save_env` находит файл по списку блоков и пишет в те же
секторы, а замена файла новым (rename) на FAT перенесла бы его в другие.
Значения с `\\` и переводом строки GRUB экранирует; нашим они не нужны,
поэтому такие значения просто отвергаются, а не экранируются.
"""
from __future__ import annotations

import os

SIZE = 1024
HEADER = b"# GRUB Environment Block\n"
#: Вторая строка, которую пишет `grub-editenv` (GRUB 2.12): сохраняем, чтобы
#: блок после нас был побайтно таким же, как после него.
WARNING = b"# WARNING: Do not edit this file by tools other than grub-editenv!!!\n"


class GrubEnvError(Exception):
    pass


def parse(block: bytes) -> dict[str, str]:
    if not block.startswith(HEADER):
        raise GrubEnvError("это не блок переменных GRUB: нет заголовка")
    values: dict[str, str] = {}
    for line in block[len(HEADER):].split(b"\n"):
        if not line or line.startswith(b"#"):
            continue
        name, sep, value = line.partition(b"=")
        if sep:
            values[name.decode("ascii", "replace")] = value.decode("utf-8", "replace")
    return values


def render(values: dict[str, str]) -> bytes:
    body = bytearray(HEADER + WARNING)
    for name, value in values.items():
        if not name or "=" in name or any(c in name + value for c in "\\\n"):
            raise GrubEnvError(f"переменную {name!r} не записать в grubenv")
        body += f"{name}={value}\n".encode()
    if len(body) > SIZE:
        raise GrubEnvError("переменные не помещаются в 1024 байта grubenv")
    return bytes(body) + b"#" * (SIZE - len(body))


def read(path: str) -> dict[str, str]:
    with open(path, "rb") as handle:
        return parse(handle.read(SIZE))


def update(path: str, set_values: dict[str, str] | None = None, unset: tuple = ()) -> dict[str, str]:
    """Поменять переменные и записать блок на место. Возвращает итог."""
    with open(path, "r+b") as handle:
        block = handle.read()
        if len(block) != SIZE:
            raise GrubEnvError(f"grubenv длиной {len(block)} байт, а не {SIZE}")
        values = parse(block)
        for name in unset:
            values.pop(name, None)
        values.update(set_values or {})
        handle.seek(0)
        handle.write(render(values))
        handle.flush()
        os.fsync(handle.fileno())
    return values
