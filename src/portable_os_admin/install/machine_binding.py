"""Привязка носителя к машинам, на которых ему разрешено работать.

Смысл -- уменьшить вероятность того, что найденный или украденный носитель
заработает на машине злоумышленника. LUKS закрывает случай «фразы нет»; это
закрывает случай «фраза есть, но носитель уже израсходовал свои слоты».

Почему это ключи, а не проверка
-------------------------------

Первая версия хранила список машин файлом на зашифрованном корне и сверяла его
в initramfs. Так делать нельзя, и возражение было точным: пользователь к этому
моменту уже ввёл фразу, том открыт, и всё, что мешает злоумышленнику, --
программная проверка, которую он снимает, смонтировав том с другого носителя и
удалив файл.

Поэтому привязка живёт в заголовке LUKS:

* **у каждой зарегистрированной машины свой keyslot**, пароль которого
  выводится из фразы и отпечатка машины: ``sha256(фраза ‖ отпечаток)``;
* пока слоты не исчерпаны, существует **регистрационный слот** с самой фразой
  -- им носитель открывается на новой машине, чтобы завести ей собственный;
* **как только занят последний слот, регистрационный уничтожается.**

После этого на незарегистрированной машине том не открывается вообще: ключа
для неё в заголовке нет. Это свойство заголовка, а не поведение программы, --
его не обойти ни другим носителем, ни правкой файлов, ни отключением нашего
модуля в initramfs. Модуль нужен только для удобства: посчитать отпечаток и
подставить готовый ключ, чтобы пользователь вводил фразу один раз.

Цена, названная честно: **пока остаются свободные слоты, фраза открывает том
на любой машине**. Иначе зарегистрировать новую машину было бы нечем. Гарантия
появляется на заполненном носителе -- и именно её и просят от механизма.

Отпечаток машины
----------------

DMI материнской платы плюс модель процессора. Сетевые адреса намеренно не
входят: док-станция или USB-сетевая карта меняли бы отпечаток, и одна и та же
машина занимала бы слот за слотом, пока не упёрлась бы в предел -- то есть
механизм срабатывал бы на своих вместо чужих.

Обратная сторона -- замена платы делает слот мёртвым: машина, где носитель
работал, перестаёт узнаваться, а слот остаётся занятым. Лечится сбросом, тем
же порядком, что и забытый пароль.
"""
from __future__ import annotations

#: Из чего складывается отпечаток. Порядок фиксирован: он входит в хеш, и
#: перестановка сделала бы отпечатки несравнимыми между версиями программы.
FINGERPRINT_SOURCES = (
    "/sys/class/dmi/id/board_vendor",
    "/sys/class/dmi/id/board_name",
    "/sys/class/dmi/id/board_serial",
    "/sys/class/dmi/id/product_uuid",
)

#: Раскладка keyslot'ов LUKS2. Их тридцать два, и распределены они так:
#:
#:   0        регистрационный: сама фраза. Уничтожается, когда занят
#:            последний машинный слот, -- в этом и состоит гарантия.
#:   1..7     по одному на зарегистрированную машину.
#:   8..31    одноразовые коды восстановления.
#:
#: Восстановления получают все оставшиеся слоты, а не пять и не один: каждый
#: расходуется безвозвратно, и тратятся они теперь на два разных события --
#: забытый пароль и очистку машин. Двадцать четыре обращения к администратору
#: отодвигают пересборку носителя далеко за пределы его обычного срока службы.
FIRST_MACHINE_KEYSLOT = 1
#: Последний keyslot заголовка LUKS2.
LAST_KEYSLOT = 31
#: Сколько машин носитель может запомнить в принципе: всё, что остаётся после
#: регистрационного слота и хотя бы одного кода восстановления.
MAX_SLOTS = LAST_KEYSLOT - FIRST_MACHINE_KEYSLOT


def machine_keyslots(config) -> tuple[int, ...]:
    """Слоты, отданные машинам."""
    slots = min(int(config.machine_binding.slots or 0), MAX_SLOTS)
    return tuple(range(FIRST_MACHINE_KEYSLOT, FIRST_MACHINE_KEYSLOT + slots))


def recovery_keyslots(config) -> tuple[int, ...]:
    """Слоты под одноразовые коды восстановления -- весь остаток заголовка.

    Их число зависит от того, сколько машин разрешил администратор: чем меньше
    машин, тем больше кодов, и наоборот. Отдавать остаток целиком выгодно,
    потому что код расходуется безвозвратно и тратится теперь на два разных
    события -- забытый пароль и очистку машин.
    """
    machines = machine_keyslots(config)
    first = (machines[-1] if machines else FIRST_MACHINE_KEYSLOT - 1) + 1
    return tuple(range(first, LAST_KEYSLOT + 1))

#: Запрос на сброс слотов, который пользователь читает администратору.
#: Отличается от запроса на восстановление пароля словом в середине, чтобы
#: администратор с одного взгляда видел, что у него просят.
RESET_REQUEST_KIND = "machines"


def is_enabled(config) -> bool:
    return int(getattr(config.machine_binding, "slots", 0) or 0) > 0


def fingerprint_functions() -> str:
    """Shell, считающий отпечаток машины и ключ её keyslot.

    Одной функцией на все места, где это нужно, потому что разойдись они хоть
    пробелом -- носитель перестал бы узнавать машину, на которой уже работал,
    и занимал бы ей новый слот при каждой загрузке.

    Нечитаемое поле DMI даёт пустую строку, а не пропуск строки: на части
    машин `board_serial` доступен только root'у или не заполнен вовсе, и
    отпечаток обязан получаться одинаковым при каждой загрузке, а не зависеть
    от того, сколько полей удалось прочитать.
    """
    sources = " ".join(FINGERPRINT_SOURCES)
    return f"""
poa_fingerprint_id() {{
    {{
        for source in {sources}; do
            [ -r "$source" ] && cat "$source" 2>/dev/null
            printf '\\n'
        done
        # Модель процессора, а не число ядер и не частота: они меняются от
        # настроек питания и от того, сколько ядер видит ядро.
        grep -m1 '^model name' /proc/cpuinfo 2>/dev/null | cut -d: -f2-
        printf '\\n'
    }} | sha256sum | cut -d' ' -f1
}}

# Ключ keyslot этой машины. Собственной стойкости ему не нужно: LUKS применяет
# к паролю argon2id, а отпечаток машины и не секрет -- он известен тому, у кого
# машина в руках. Задача этого значения одна: быть детерминированным.
poa_machine_key() {{
    printf '%s%s' "$1" "$(poa_fingerprint_id)" | sha256sum | cut -d' ' -f1
}}

# Первые восемь знаков отпечатка -- в консоль загрузки. Без них отказ на
# незарегистрированной машине неотличим от неверной фразы: и то, и другое
# выглядит как «пароль не подошёл». Администратору этого хватает, чтобы
# сказать, ту ли машину видит носитель, а секрета здесь нет -- отпечаток
# известен всякому, у кого машина в руках.
#
# Только в консоль и в stderr, никогда в stdout: у Debian этот же файл
# подключается как keyscript, и весь его stdout cryptsetup принимает за ключ.
# Строка «Машина: …», попавшая туда, сделала бы носитель незагружаемым.
poa_say_fingerprint() {{
    short=$(poa_fingerprint_id | cut -c1-8)
    echo "Машина: $short" > /dev/console 2>/dev/null || echo "Машина: $short" >&2
}}
"""


#: Где на носителе лежит скрипт, печатающий ключ этой машины.
KEY_SCRIPT_PATH = "usr/local/sbin/poa-machine-key"
#: Где -- скрипт регистрации, спрашивающий разрешение занять слот.
REGISTER_SCRIPT_PATH = "usr/local/sbin/poa-machine-register"


def unlock_functions(config) -> str:
    """Общая часть: спросить фразу и выбрать подходящий ключ.

    Выбор делается проверкой, а не догадкой: сначала пробуется ключ машины, и
    только если такого keyslot нет -- сама фраза. Так один и тот же код
    обслуживает и зарегистрированную машину, и первую загрузку на новой, и
    пользователь в обоих случаях вводит пароль ровно один раз.

    Проверка идёт по машинным слотам поимённо, а не по всему заголовку. Без
    `--key-slot` cryptsetup перебирает каждый занятый keyslot, а их на готовом
    носителе тридцать, и на каждый приходится отдельный argon2id на 256 МиБ --
    8,4 секунды по замерам этого проекта. Четыре минуты ожидания перед вводом
    пароля на живой машине и часы под эмуляцией: прогон 28.08.2026 на этом и
    встал. При двух разрешённых машинах проверок ровно две.
    """
    machines = machine_keyslots(config)
    first = machines[0] if machines else FIRST_MACHINE_KEYSLOT
    last = machines[-1] if machines else FIRST_MACHINE_KEYSLOT - 1
    return (
        f"""
# Слоты, отданные машинам. Только их и проверяем.
POA_FIRST_MACHINE_SLOT={first}
POA_LAST_MACHINE_SLOT={last}
"""
        + """
# Запрос фразы. askpass есть в initramfs обоих семейств; при его отсутствии
# читаем с консоли сами -- носитель не должен зависеть от того, положил ли
# дистрибутив в образ конкретную утилиту.
poa_ask_passphrase() {
    if [ -x /lib/cryptsetup/askpass ]; then
        /lib/cryptsetup/askpass "Введите пароль носителя: " || true
    elif command -v systemd-ask-password >/dev/null 2>&1; then
        # --timeout=300 вместо умолчания dracut: замерено на стенде
        # 28.08.2026 -- запрос жил 45 секунд и молча закрывался с «Failed to
        # query password: Timer expired». Столько же не хватает человеку,
        # который сперва читает, что машина носителю незнакома, а потом
        # набирает длинную фразу. Истёкший таймер здесь -- незагружаемый
        # носитель, и цена ошибки несопоставима с ожиданием.
        #
        # `|| true` -- потому что скрипт идёт под `set -e`, а неудачный ввод
        # возвращает ненулевой код: без этого первая же осечка убивала хук
        # целиком вместо того, чтобы отдать вторую и третью попытку.
        systemd-ask-password --timeout=300 "Введите пароль носителя:" || true
    else
        printf 'Введите пароль носителя: ' > /dev/console 2>/dev/null || true
        stty -echo 2>/dev/null || true
        read -r reply < /dev/console 2>/dev/null || read -r reply
        stty echo 2>/dev/null || true
        echo > /dev/console 2>/dev/null || true
        printf '%s' "$reply"
    fi
}

# Номер слота этой машины, если он есть, иначе пусто.
#
# Каждый слот проверяется поимённо, через --key-slot. Без него cryptsetup
# перебирает весь заголовок, а занятых слотов на готовом носителе тридцать, и
# каждый -- отдельный argon2id на 256 МиБ. Восемь секунд на слот превращаются
# в четыре минуты ожидания перед вводом пароля, а под эмуляцией -- в часы:
# прогон 28.08.2026 на этом и встал, выглядело это как зависшая загрузка.
poa_machine_slot() {  # $1 -- устройство, $2 -- ключ машины
    ( umask 077; printf '%s' "$2" > /run/poa-try.key )
    poa_slot="$POA_FIRST_MACHINE_SLOT"
    while [ "$poa_slot" -le "$POA_LAST_MACHINE_SLOT" ]; do
        if cryptsetup luksOpen --test-passphrase --key-slot "$poa_slot" \
                --key-file /run/poa-try.key "$1" 2>/dev/null; then
            rm -f /run/poa-try.key
            printf '%s' "$poa_slot"
            return 0
        fi
        poa_slot=$((poa_slot + 1))
    done
    rm -f /run/poa-try.key
    return 0
}

# Ключ, которым этот носитель открывается на этой машине. Печатает ключ
# машины, если её keyslot существует, иначе саму фразу -- она подойдёт, пока
# жив регистрационный слот, и не подойдёт, когда он уничтожен. Второе и есть
# отказ на незарегистрированной машине.
poa_unlock_key() {  # $1 -- устройство, $2 -- фраза
    machine=$(poa_machine_key "$2")
    if [ -n "$(poa_machine_slot "$1" "$machine")" ]; then
        printf '%s' "$machine"
    else
        printf '%s' "$2"
    fi
}
"""
    )


def key_script(config) -> str:
    """Печатает ключ keyslot этой машины -- и больше ничего.

    Одна обязанность и никакого диалога: этот скрипт вызывают там, где
    спрашивать некого. У Debian это `keyscript=` из crypttab, чей вывод
    cryptsetup берёт как ключ; у RHEL -- агент паролей systemd, который тем же
    значением отвечает в сокет запроса.

    Молчание при неудаче -- часть механизма, а не небрежность. Агенты паролей
    systemd работают наперегонки: кто ответил первым, тот и выиграл, а кто не
    ответил, тот просто не мешает. Поэтому на незнакомой машине скрипт не
    печатает ничего, запрос достаётся штатному агенту, и пользователь вводит
    фразу как обычно. Ошибись здесь -- и носитель перестал бы грузиться вместо
    того, чтобы спросить пароль.
    """
    if not is_enabled(config):
        return ""
    return f"""#!/bin/sh
# generated by portable-os-admin
# keyscript для crypttab: печатает в stdout ключ, которым открывается том.
#
# Вызывается cryptsetup-initramfs вместо запроса пароля. Спрашивает фразу сам,
# потому что ключ машины из неё и выводится, и печатает подходящий: ключ
# машины, если её keyslot есть, иначе саму фразу.
set -eu

{fingerprint_functions()}
{unlock_functions(config)}

device="${{CRYPTTAB_SOURCE:-$1}}"
poa_say_fingerprint
passphrase=$(poa_ask_passphrase)
[ -n "$passphrase" ] || exit 0

# Фраза остаётся доступной шагу регистрации: он идёт следом, в той же
# загрузке, и второй запрос пароля выглядел бы как сбой. Файл живёт в tmpfs
# initramfs и на носитель не попадает.
( umask 077; printf '%s' "$passphrase" > /run/poa-passphrase )

poa_unlock_key "$device" "$passphrase"
"""


def register_script(config, media_id: str) -> str:
    """Спрашивает разрешение занять слот и заводит keyslot этой машины.

    Запускается после того, как том уже открыт: на незнакомой машине это
    происходит регистрационной фразой. Отдельно от подстановки ключа, потому
    что обязанности разные -- та молча отвечает на запрос, эта разговаривает с
    человеком и меняет заголовок LUKS.
    """
    if not is_enabled(config):
        return ""
    machines = machine_keyslots(config)
    return f"""#!/bin/sh
# generated by portable-os-admin
# Регистрация машины: спрашивает разрешение и заводит ей keyslot.
set -eu

MEDIA_ID={media_id}
SLOTS={len(machines)}
FIRST_SLOT={machines[0] if machines else FIRST_MACHINE_KEYSLOT}
LAST_SLOT={machines[-1] if machines else FIRST_MACHINE_KEYSLOT}
: "${{POA_LUKS_UUID:?не задан POA_LUKS_UUID}}"
: "${{POA_USER_SLOT:=0}}"

device="/dev/disk/by-uuid/${{POA_LUKS_UUID}}"
KEY=/run/poa-reg.key
NEWKEY=/run/poa-reg-new.key

cleanup() {{ rm -f "$KEY" "$NEWKEY"; }}
trap cleanup EXIT INT TERM

{fingerprint_functions()}

say() {{ echo "$1" > /dev/console 2>/dev/null || echo "$1"; }}
ask() {{ printf '%s' "$1" > /dev/console 2>/dev/null || printf '%s' "$1"; }}

# Выключение, а не продолжение: смысл механизма в том, что на машине, которую
# пользователь отказался регистрировать, система не работает.
halt_now() {{
    say ""
    say "$1"
    sleep 5
    poweroff -f 2>/dev/null || echo o > /proc/sysrq-trigger
    exit 1
}}

slot_taken() {{  # $1 -- номер слота
    cryptsetup luksDump "$device" 2>/dev/null | grep -qE "^[[:space:]]+$1: luks2"
}}

[ -b "$device" ] || exit 0
[ -n "${{POA_PASSPHRASE:-}}" ] || exit 0

# Ключ этой машины уже есть -- значит она зарегистрирована, и делать нечего.
#
# Проверяются только машинные слоты, поимённо. Без --key-slot cryptsetup
# перебирает весь заголовок -- тридцать занятых слотов, каждый со своим
# argon2id на 256 МиБ, -- и это на каждой загрузке уже зарегистрированной
# машины, то есть в самом частом случае. Та же ошибка была в разблокировке и
# там же измерена: четыре минуты на живом железе, часы под эмуляцией.
( umask 077; poa_machine_key "$POA_PASSPHRASE" > "$KEY" )
poa_slot=$FIRST_SLOT
while [ "$poa_slot" -le "$LAST_SLOT" ]; do
    if cryptsetup luksOpen --test-passphrase --key-slot "$poa_slot" \
            --key-file "$KEY" "$device" 2>/dev/null; then
        exit 0
    fi
    poa_slot=$((poa_slot + 1))
done

used=0
free_slot=""
slot="$FIRST_SLOT"
while [ "$slot" -le "$LAST_SLOT" ]; do
    if slot_taken "$slot"; then
        used=$((used + 1))
    elif [ -z "$free_slot" ]; then
        free_slot="$slot"
    fi
    slot=$((slot + 1))
done

if [ -z "$free_slot" ]; then
    # Сюда попасть можно только если регистрационный слот ещё жив, а машинные
    # кончились: несогласованное состояние, но выпускать пользователя в
    # систему на незарегистрированной машине всё равно нельзя.
    halt_now "Свободных слотов не осталось. Обратитесь к администратору."
fi

say ""
say "======================================================================"
say " Эта машина носителю незнакома."
say ""
say " Отпечаток машины: $(poa_fingerprint_id | cut -c1-8)"
say " Занято слотов: $used из $SLOTS, свободно: $((SLOTS - used))."
say ""
say " Если продолжить, конфигурация этой машины будет записана в носитель"
say " и займёт один слот. Освободить его потом можно будет ТОЛЬКО с"
say " участием администратора организации."
say "======================================================================"
say ""
ask "Внести эту машину в память носителя? (да/нет): "
read -r answer < /dev/console 2>/dev/null || read -r answer
case "$answer" in
    да|Да|ДА|yes|Yes|y|Y|д|Д) ;;
    *) halt_now "Машина не внесена. Система не запускается." ;;
esac

( umask 077; printf '%s' "$POA_PASSPHRASE" > "$KEY" )
( umask 077; poa_machine_key "$POA_PASSPHRASE" > "$NEWKEY" )
if ! cryptsetup luksAddKey "$device" "$NEWKEY" --pbkdf-memory 262144 \
        --key-slot "$free_slot" --key-file "$KEY" 2>/dev/null; then
    halt_now "Не удалось записать машину в носитель."
fi
say "Машина внесена (слот $free_slot)."

# Занят последний слот -- регистрационный ключ уничтожается. Именно этот шаг
# превращает механизм из проверки в гарантию: с этого момента одна лишь фраза
# не открывает том нигде, потому что подходящего keyslot больше нет.
if [ $((used + 1)) -ge "$SLOTS" ]; then
    if cryptsetup luksKillSlot "$device" "$POA_USER_SLOT" --batch-mode \
            --key-file "$NEWKEY" 2>/dev/null; then
        say "Занят последний слот: носитель работает только на записанных машинах."
    else
        say "ВНИМАНИЕ: регистрационный ключ не удалён, привязка не завершена." >&2
    fi
fi

cleanup
exit 0
"""


def dracut_unlock_script(config, mapper_name: str) -> str:
    """Открывает том на RHEL-семействе -- вместо systemd-cryptsetup, не после.

    Агент паролей systemd, которым решает эту задачу clevis, здесь не
    подходит: агент отвечает *вместо* пользователя, а наш ключ выводится из
    его фразы, и спросить её агенту негде. Перехватить же systemd-cryptsetup
    порядком хуков нельзя -- dracut прямо документирует, что в systemd-режиме
    приоритеты хуков не соблюдаются, и построенное на них решение ломалось бы
    непредсказуемо.

    Поэтому systemd-cryptsetup для этого тома не запускается вовсе: при
    включённой привязке `rd.luks.uuid` в командную строку не пишется, и том
    открывает этот хук. Путь наружу при его отказе остаётся -- модуль
    восстановления работает следом, в том же pre-mount.
    """
    if not is_enabled(config):
        return ""
    return f"""#!/bin/sh
# generated by portable-os-admin
# Разблокировка тома с учётом привязки к машине.
set -eu

: "${{POA_LUKS_UUID:?не задан POA_LUKS_UUID}}"
device="/dev/disk/by-uuid/${{POA_LUKS_UUID}}"

# Уже открыт -- значит этот хук отработал раньше или том открыли иначе.
[ -b "/dev/mapper/{mapper_name}" ] && exit 0

# Ждём сам накопитель, а не выходим молча. udev успокаивается раньше, чем
# появляется USB-устройство: замерено на стенде 28.08.2026 -- initqueue
# завершился на 11,55 секунде, а sda обнаружился на 12,5. Хук отрабатывал
# вхолостую, том оставался закрытым, и systemd потом две с половиной минуты
# ждал корневое устройство, которого без нас не будет.
poa_waited=0
while [ ! -b "$device" ] && [ "$poa_waited" -lt 60 ]; do
    sleep 1
    poa_waited=$((poa_waited + 1))
done
[ -b "$device" ] || exit 0

{fingerprint_functions()}
{unlock_functions(config)}

poa_say_fingerprint

attempt=1
while [ "$attempt" -le 3 ]; do
    passphrase=$(poa_ask_passphrase)
    if [ -n "$passphrase" ]; then
        # Слот известен заранее, и открываем строго его. Без --key-slot
        # cryptsetup перебирает весь заголовок -- тридцать занятых слотов на
        # готовом носителе, каждый со своим argon2id на 256 МиБ. Хуже всего
        # это било по отказу: на незарегистрированной машине ключ не подходит
        # никуда, перебор идёт до конца и повторяется трижды. Замерено на
        # стенде 28.08.2026 -- одиннадцать минут на одну попытку, и всё это
        # время экран выглядит зависшим. Теперь отказ мгновенный: слота нет --
        # значит нет.
        machine_key=$(poa_machine_key "$passphrase")
        slot=$(poa_machine_slot "$device" "$machine_key")
        if [ -n "$slot" ]; then
            key="$machine_key"
        else
            # Регистрационный слот. Когда он уничтожен -- а это и означает
            # исчерпанный носитель, -- открывать нечем, и проверять больше
            # нечего.
            slot="${{POA_USER_SLOT:-0}}"
            key="$passphrase"
        fi
        ( umask 077; printf '%s' "$key" > /run/poa-unlock.key )
        if cryptsetup luksOpen --key-slot "$slot" --key-file /run/poa-unlock.key \
                "$device" "{mapper_name}" 2>/dev/null; then
            rm -f /run/poa-unlock.key
            # Фразу оставляем шагу регистрации: он идёт следом, в этой же
            # загрузке, и второй запрос пароля выглядел бы как сбой.
            ( umask 077; printf '%s' "$passphrase" > /run/poa-passphrase )
            exit 0
        fi
        rm -f /run/poa-unlock.key
    fi
    echo "Пароль не подошёл." > /dev/console 2>/dev/null || true
    attempt=$((attempt + 1))
done

# Три попытки исчерпаны. Дальше очередь модуля восстановления -- он и объяснит
# пользователю, что делать, вместо голого «cryptsetup failed».
exit 0
"""
