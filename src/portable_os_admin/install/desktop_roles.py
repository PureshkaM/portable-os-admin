#: Имя среды -> её роли.
ROLES: dict[str, tuple[Role, ...]] = {"mate": MATE_ROLES}


def packages_for(
    desktop: str,
    *,
    overrides: dict[str, dict[str, str]] | None = None,
    extras: dict[str, tuple[str, ...]] | None = None,
    blank_screen: bool = False,
) -> list[str]:
    """Пакеты рабочей среды: роли плюс исключения семейства.

    `overrides` -- «эта роль у нас называется иначе», по одной записи на роль,
    а не переписанный список: чем короче исключение, тем виднее, чем системы
    действительно различаются. Пустая строка означает «эта роль у нас не
    нужна»; так `lightdm-gtk-greeter` не приходится выдумывать роли, а
    ненужное можно снять, не ломая общий набор.

    `extras` -- то, чему роли нет: пакет, существующий у одного семейства и не
    имеющий пары у другого. Список короткий намеренно -- если он растёт, значит
    роль всё-таки есть, и её надо назвать.
    """
    roles = ROLES.get(desktop)
    if roles is None:
        return []
    per_desktop_overrides = (overrides or {}).get(desktop, {})
    packages: list[str] = []
    for role in roles:
        if role.optional and role.key == "screen-blanking" and not blank_screen:
            continue
        name = per_desktop_overrides.get(role.key, role.package)
        if not name:
            # Роль, которой у этого семейства нет. Молчаливое «нет» здесь
            # законно: за него отвечает бэкенд, назвавший её пустой строкой.
            continue
        packages.append(name)
    packages += list((extras or {}).get(desktop, ()))
    return packages


def role_of(desktop: str, package: str, overrides: dict[str, dict[str, str]] | None = None) -> str:
    """Роль, которую исполняет этот пакет, или пустая строка.

    Нужна для сообщений: «не поставился mate-desktop» ничего не говорит, а «не
    поставились схемы настроек» объясняет, почему сеанс не поднимется.
    """
    per_desktop_overrides = (overrides or {}).get(desktop, {})
    for role in ROLES.get(desktop, ()):
        name = per_desktop_overrides.get(role.key, role.package)
        if name == package:
            return role.key
    return ""


