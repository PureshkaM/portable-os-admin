"""Из чего состоит рабочая среда киоска -- ролями, а не списками пакетов.

Зачем это отдельный модуль. За четыре живых прогона 01--02.09.2026 набралось
несколько правок, сделанных дважды -- по разу на семейство, -- и каждая была
одной и той же мыслью, записанной в двух файлах. Замер на 02.09.2026: наборы
MATE у РЕД ОС и Debian совпадали на десять пакетов из двенадцати (тогда была ещё
и среда KDE, упразднённая 01.10.2026), а двадцать строк объяснения, почему в наборе стоит
`mate-desktop`, лежали в обоих бэкендах слово в слово.

Дублирование здесь опаснее обычного: правку, найденную на одной системе, легко
внести в один файл и забыть про второй, а обнаружится это только живой
загрузкой -- через сборку, запись и семь минут ожидания. Ровно так и был
потерян пакет схем GSettings.

Поэтому среда описывается **ролями**: «менеджер сеанса», «панель», «схемы
настроек», «апплет сети». Роль -- это ответ на вопрос «зачем эта строка в
наборе», и он один для обоих семейств. Меняется только имя пакета, и только там,
где оно у дистрибутива действительно своё: бэкенд объявляет исключения, а не
переписывает список.

Объяснения живут здесь же, рядом с ролью, а не в бэкенде. Тогда найденное
однажды читается один раз и относится к обеим системам сразу.
"""
from __future__ import annotations

from dataclasses import dataclass

#: Роль, которую в собранной системе кто-то должен исполнять.
#:
#: `why` -- не украшение: набор пакетов киоска собран вручную именно затем,
#: чтобы в системе не было ничего лишнего, и каждая строка обязана объяснить,
#: почему она не лишняя. Текст попадает в документацию и в обзор конфигурации.
@dataclass(frozen=True)
class Role:
    key: str
    #: Имя пакета, если оно одинаково у обоих семейств.
    package: str
    why: str
    #: Роль нужна не всегда: гашение экрана ставится только когда его просят.
    optional: bool = False


