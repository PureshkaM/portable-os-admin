"""Э9 вручную: выпуск из каталога дистрибутива -- в неактивный слот носителя."""
from __future__ import annotations

import hashlib
import json
import time

import pytest
from cryptography.hazmat.primitives.asymmetric import ed25519

from portable_os_admin.admin import media_update
from portable_os_admin.install import grubenv
from portable_os_admin.install.access.runtime import poa_gost, poa_trust

FILES = {"rootfs.squashfs": b"image" * 1000, "rootfs.verity": b"tree" * 10,
         "vmlinuz": b"kernel" * 100, "initrd.img": b"initrd" * 100}
KEYS = {"rootfs.squashfs": "image", "rootfs.verity": "verity", "vmlinuz": "kernel", "initrd.img": "initrd"}


def _payload(serial, family="debian"):
    body = {"kind": "poa-release", "format": 1, "serial": serial, "name": "kiosk", "family": family,
            "arch": "amd64", "layout": 3, "verity_root_hash": "ab" * 32}
    for name, data in FILES.items():
        body[KEYS[name]] = {"file": name, "sha256": hashlib.sha256(data).hexdigest(), "size": len(data)}
    return body


def test_grubenv_round_trip_keeps_the_block_size(tmp_path):
    path = tmp_path / "grubenv"
    path.write_bytes(grubenv.render({"poa_good": "a"}))
    assert len(path.read_bytes()) == 1024
    grubenv.update(str(path), {"poa_try": "b", "poa_tries": "3"})
    assert grubenv.read(str(path)) == {"poa_good": "a", "poa_try": "b", "poa_tries": "3"}
    grubenv.update(str(path), unset=("poa_try", "poa_tries"))
    assert grubenv.read(str(path)) == {"poa_good": "a"}
    assert len(path.read_bytes()) == 1024


def test_grubenv_matches_grub_editenv_layout():
    # Так выглядит блок после `grub-editenv grubenv create; ... set poa_good=a`
    # (снят с носителя стенда 03.10.2026).
    head = (b"# GRUB Environment Block\n"
            b"# WARNING: Do not edit this file by tools other than grub-editenv!!!\npoa_good=a\n")
    block = grubenv.render({"poa_good": "a"})
    assert block.startswith(head) and set(block[len(head):]) == {ord("#")}
    with pytest.raises(grubenv.GrubEnvError):
        grubenv.render({"x": "a\nb"})


@pytest.fixture
def medium(tmp_path):
    root = poa_trust.GostSigner(poa_gost.new_private_key(poa_gost.TC26_256_A), "main")
    working = ed25519.Ed25519PrivateKey.generate()
    cert = poa_trust.certify(root, poa_trust.raw_public(working), time.time() + 3600, 1)
    esp, boot, images, dist = (tmp_path / n for n in ("esp", "boot", "images", "dist"))
    (esp / "EFI/poa").mkdir(parents=True)
    (esp / "EFI/poa/grubenv").write_bytes(grubenv.render({"poa_good": "a"}))
    (boot / "slot-a").mkdir(parents=True)
    (boot / "slot-a" / "release.json").write_text(json.dumps({"release": _payload(10)}))
    (boot / "slot-a" / "vmlinuz").write_bytes(b"old kernel")
    (images / "slot-a").mkdir(parents=True)
    dist.mkdir()
    for name, data in FILES.items():
        (dist / name).write_bytes(data)

    def publish(payload):
        (dist / "release.json").write_text(json.dumps(poa_trust.sign_document(working, cert, "release", payload)))

    return [root.entry], publish, esp, boot, images, dist


def _write(anchors, esp, boot, images, dist):
    payload = media_update.load_release(str(dist), anchors, b"")
    return media_update.write_slot(str(dist), payload, str(esp), str(boot), str(images))


def test_a_newer_release_goes_to_the_free_slot_and_is_offered_to_grub(medium):
    anchors, publish, esp, boot, images, dist = medium
    publish(_payload(11))
    seen = []
    payload = media_update.load_release(str(dist), anchors, b"")
    result = media_update.write_slot(str(dist), payload, str(esp), str(boot), str(images),
                                     lambda done, total: seen.append((done, total)))
    assert result == {"slot": "b", "serial": 11, "name": "kiosk", "previous": 10}
    assert (images / "slot-b" / "rootfs.squashfs").read_bytes() == FILES["rootfs.squashfs"]
    assert (boot / "slot-b" / "initrd.img").read_bytes() == FILES["initrd.img"]
    assert "set poa_serial=11" in (boot / "slot-b" / "slot.cfg").read_text()
    assert json.loads((boot / "slot-b" / "release.json").read_text())["release"]["serial"] == 11
    assert grubenv.read(str(esp / "EFI/poa/grubenv")) == {"poa_good": "a", "poa_try": "b", "poa_tries": "3"}
    assert (boot / "slot-a" / "vmlinuz").read_bytes() == b"old kernel"     # рабочий слот цел
    assert seen[-1][0] == seen[-1][1] == sum(len(d) for d in FILES.values())
    assert not list(images.rglob("*.part")) and not list(boot.rglob("*.part"))


def test_an_older_or_foreign_release_is_refused_before_touching_the_medium(medium):
    anchors, publish, esp, boot, images, dist = medium
    publish(_payload(10))
    with pytest.raises(media_update.MediaUpdateError, match="не новее"):
        _write(anchors, esp, boot, images, dist)
    publish(_payload(11, family="redos"))
    with pytest.raises(media_update.MediaUpdateError, match="несовместим"):
        _write(anchors, esp, boot, images, dist)
    assert not (boot / "slot-b").exists()


def test_a_release_signed_by_a_stranger_is_refused(medium):
    _anchors, publish, esp, boot, images, dist = medium
    publish(_payload(11))
    stranger = poa_trust.GostSigner(poa_gost.new_private_key(poa_gost.TC26_256_A), "main")
    with pytest.raises(media_update.MediaUpdateError, match="подписи"):
        _write([stranger.entry], esp, boot, images, dist)


def test_a_damaged_file_leaves_grub_without_the_offer(medium):
    anchors, publish, esp, boot, images, dist = medium
    publish(_payload(11))
    (dist / "vmlinuz").write_bytes(b"X" * len(FILES["vmlinuz"]))
    with pytest.raises(media_update.MediaUpdateError, match="sha256"):
        _write(anchors, esp, boot, images, dist)
    assert "poa_try" not in grubenv.read(str(esp / "EFI/poa/grubenv"))
    assert not (boot / "slot-b" / "release.json").exists()


def test_a_pending_offer_of_the_slot_is_withdrawn_before_it_is_rewritten(medium, monkeypatch):
    """Слот B уже предложен (прошлая запись), запись нового срывается на
    середине: GRUB не должен пробовать полуслот."""
    anchors, publish, esp, boot, images, dist = medium
    publish(_payload(11))
    _write(anchors, esp, boot, images, dist)
    publish(_payload(12))

    def broken(*_args):
        raise OSError("флешку выдернули")

    monkeypatch.setattr(media_update, "_copy", broken)
    with pytest.raises(OSError):
        _write(anchors, esp, boot, images, dist)
    assert grubenv.read(str(esp / "EFI/poa/grubenv")) == {"poa_good": "a"}


def test_a_medium_without_slots_is_explained(medium):
    anchors, publish, esp, boot, images, dist = medium
    publish(_payload(11))
    (esp / "EFI/poa/grubenv").unlink()
    with pytest.raises(media_update.MediaUpdateError, match="перезаписью"):
        _write(anchors, esp, boot, images, dist)
