DRAWIO = "/Applications/draw.io.app/Contents/MacOS/draw.io"
#: Вкладки, которым нужна автоматическая раскладка draw.io (номер с нуля → вид раскладки).
AUTO_LAYOUT = {1: "verticalFlow"}


def apply_layouts(path: str) -> None:
    """Прогоняет выбранные вкладки через раскладку draw.io (ELK) и вставляет обратно."""
    cli = shutil.which("drawio") or (DRAWIO if os.path.exists(DRAWIO) else None)
    if not cli:
        print("draw.io Desktop не найден — вкладки остаются с ручной раскладкой")
        return
    data = open(path, encoding="utf-8").read()
    diagrams = re.findall(r"<diagram .*?</diagram>", data, re.S)
    with tempfile.TemporaryDirectory() as tmp:
        for index, layout in AUTO_LAYOUT.items():
            src, dst = os.path.join(tmp, "in.drawio"), os.path.join(tmp, "out.drawio")
            with open(src, "w", encoding="utf-8") as fh:
                fh.write('<mxfile host="Electron">' + diagrams[index] + "</mxfile>")
            subprocess.run([cli, "-x", "-f", "xml", "--layout", layout, "-o", dst, src],
                           check=True, capture_output=True, timeout=120)
            laid = re.search(r"<diagram .*?</diagram>", open(dst, encoding="utf-8").read(), re.S)
            data = data.replace(diagrams[index], laid.group(0))
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(data)


def main() -> None:
    out = sys.argv[1]
    pages = [entities_page(), relations_page(), architecture_page(), usecases_page()]
    pages += processes()
    pages.append(findings_page())
    write(out, pages)
    apply_layouts(out)
    print(f"{out}: {len(pages)} вкладок")


if __name__ == "__main__":
    main()
