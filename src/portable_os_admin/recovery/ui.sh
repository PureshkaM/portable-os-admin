#!/bin/sh
# poa/ui.sh -- то, чем носитель разговаривает с человеком до загрузки системы.
#
# Подключается всеми компонентами загрузочной среды: разблокировкой тома,
# регистрацией машины, восстановлением пароля и сбросом списка машин. Экран
# один и тот же, а вызывают его разные части -- поэтому он и вынесен сюда, а
# не написан в каждой по-своему.
#
# Почему через plymouth
# ---------------------
#
# Своя отрисовка на framebuffer означала бы собственный графический стек в
# initramfs -- шрифты, раскладку, ввод -- в самом хрупком месте загрузки, где
# ошибка стоит незагружаемого носителя. plymouth уже лежит в образе (он есть в
# списке модулей dracut), умеет ровно три нужные вещи -- показать сообщение,
# спросить пароль со звёздочками и задать вопрос -- и рисует своим шрифтом.
#
# Последнее важнее, чем кажется: до этого сообщения печатались в консоль ядра,
# а она не знает кириллицы, и весь текст шёл сплошными блоками. Русская
# система, объясняющая пользователю блоками, что делать, -- хуже, чем
# молчащая.
#
# Запасной путь -- консоль. Он не «на всякий случай»: plymouth выключают
# параметром ядра, и носитель обязан оставаться работоспособным. Тогда текст
# идёт как раньше, блоками, но человек хотя бы дойдёт до администратора.

# Работает ли plymouth прямо сейчас. Проверяется каждый раз, а не однажды:
# демон может не подняться на машине с необычной видеокартой, и узнать об
# этом лучше до того, как вопрос уйдёт в никуда и загрузка встанет навсегда.
poa_ui_active() {
    command -v plymouth >/dev/null 2>&1 && plymouth --ping >/dev/null 2>&1
}

# Сообщение во весь экран. Переводы строк plymouth понимает, поэтому текст
# передаётся как есть.
poa_say() {
    if poa_ui_active; then
        plymouth display-message --text="$1"
    else
        echo "$1" > /dev/console 2>/dev/null || echo "$1"
    fi
}

# Убрать показанное сообщение. Без этого они накапливаются поверх друг друга:
# plymouth держит каждое, пока его не снимут.
poa_clear() {
    if poa_ui_active; then
        plymouth hide-message --text="$1" 2>/dev/null || true
    fi
}

# Ввод, который видно. Для кода восстановления: человек переписывает его с
# бумажки и должен видеть, что набрал.
poa_ask() {
    if poa_ui_active; then
        plymouth ask-question --prompt="$1"
    else
        printf '%s ' "$1" > /dev/console 2>/dev/null || printf '%s ' "$1"
        read -r poa_reply < /dev/console 2>/dev/null || read -r poa_reply
        printf '%s' "$poa_reply"
    fi
}

# Ввод, который не видно, -- пароль. plymouth сам рисует звёздочки.
poa_ask_secret() {
    if poa_ui_active; then
        plymouth ask-for-password --prompt="$1"
    else
        printf '%s ' "$1" > /dev/console 2>/dev/null || printf '%s ' "$1"
        stty -echo 2>/dev/null || true
        read -r poa_reply < /dev/console 2>/dev/null || read -r poa_reply
        stty echo 2>/dev/null || true
        echo > /dev/console 2>/dev/null || true
        printf '%s' "$poa_reply"
    fi
}

# Вопрос, на который отвечают согласием. Ответ разбирается здесь, а не у
# вызывающего: раскладка консоли -- латинская, и кириллическое «да» пользователю
# набрать нечем. Принимается и то, и другое -- на случай, если раскладка всё
# же русская.
poa_confirm() {
    poa_answer=$(poa_ask "$1 (да/нет, yes/no):")
    case "$poa_answer" in
        да|Да|ДА|д|Д|yes|Yes|YES|y|Y) return 0 ;;
        *) return 1 ;;
    esac
}
