"""Экран, которым носитель разговаривает с человеком до загрузки.

Плагин приходит параметром, а не читается у объекта: у семейств он разный
(`two-step` у РЕД ОС, `script` у Debian), но облик носителя один, и написан он
здесь в единственном экземпляре.
"""
from __future__ import annotations

from ..constants import PLYMOUTH_THEME_NAME


def theme(plugin: str) -> str:
    """Описание темы для того плагина, который есть в образе.

    Белый текст на чёрном и ничего больше: ни логотипа, ни полосы, ни
    анимации. Экран показывается в двух случаях -- когда спрашивают пароль
    и когда что-то пошло не так, -- и в обоих внимание должно быть на
    тексте.

    Плагин `two-step`, а не `script`. Выбор сделан не по вкусу: `script`
    даёт полный контроль, но его плагина нет в образе РЕД ОС вовсе, а
    собирать носитель из сети этот проект принципиально не умеет. Есть
    `two-step` (фон и картинки) и `label` (текст) -- на них тема и
    строится, целиком через ключи, без собственного кода.

    Картинок в теме ровно столько, сколько нужно плагину, чтобы
    показать запрос пароля: рамка поля и точка набранного знака,
    копируются при развёртывании из любой темы, найденной в образе.
    Без них `two-step` не рисует запрос вовсе и plymouth уходит в
    текстовый режим. Ни логотипа, ни фоновых изображений под
    разрешения экрана здесь нет.
    """
    if plugin == "script":
        return theme_for_script()
    return (
        "# generated by portable-os-admin\n"
        "[Plymouth Theme]\n"
        "Name=Portable OS\n"
        "Description=Белый текст на чёрном: пароль, компьютер, восстановление\n"
        "ModuleName=two-step\n"
        "\n"
        "[two-step]\n"
        f"ImageDir=/usr/share/plymouth/themes/{PLYMOUTH_THEME_NAME}\n"
        # Чёрный сверху донизу: градиента нет, потому что нечему отвлекать.
        "BackgroundStartColor=0x000000\n"
        "BackgroundEndColor=0x000000\n"
        # Всё по центру экрана -- и вопрос, и поле ввода, и сообщения.
        "DialogHorizontalAlignment=.5\n"
        "DialogVerticalAlignment=.5\n"
        "TitleHorizontalAlignment=.5\n"
        "TitleVerticalAlignment=.5\n"
        # Сообщения -- под диалогом, а не в левом верхнем углу.
        #
        # Здесь стояли `MessageHorizontalAlignment` и
        # `MessageVerticalAlignment`, и они не делали ничего: плагин
        # `two-step` таких ключей не знает вовсе. Выяснено 31.08.2026
        # осмотром самого плагина (`strings two-step.so`) -- он читает
        # `MessageBelowAnimation`, и это единственное, чем положение
        # сообщений вообще управляется. До этого объяснение, почему
        # компьютер незнаком, и причина восстановления печатались в углу,
        # мелко и мимо взгляда.
        "MessageBelowAnimation=true\n"
        # Белый текст. Указывается отдельно от фона: по умолчанию plymouth
        # берёт цвет темы дистрибутива, а она у РЕД ОС своя.
        "TitleColor=0xffffff\n"
        "MessageColor=0xffffff\n"
        "PasswordColor=0xffffff\n"
        # Шрифт назван явно. Без него plymouth берёт умолчание, а в
        # initramfs шрифтов нет вовсе -- и текст рисуется прямоугольниками
        # вместо букв. DejaVu выбран потому, что он есть в образе и знает
        # кириллицу: ею тут написано всё.
        "Font=DejaVu Sans 12\n"
        "TitleFont=DejaVu Sans 14\n"
        # Поле ввода: рамка и точки по числу набранных знаков. Плагин
        # рисует его из готовых картинок, которые кладутся в каталог темы
        # при развёртывании (см. installer). Без них он не может показать
        # запрос вовсе и plymouth уходит в текстовый режим -- найдено
        # прогоном 29.08.2026, и по экрану это выглядело просто как
        # «графика не включилась».
        "UseEndAnimation=false\n"
        "UseFirmwareBackground=false\n"
    )


def theme_for_script() -> str:
    """То же описание экрана, но для плагина `script`.

    Ключей у него нет вовсе: плагин выполняет скрипт темы, и всё, что в
    `two-step` задавалось строчкой, здесь пишется кодом. Отсюда и
    `ScriptFile` -- единственное, что этот файл сообщает плагину.
    """
    theme_dir = f"/usr/share/plymouth/themes/{PLYMOUTH_THEME_NAME}"
    return (
        "# generated by portable-os-admin\n"
        "[Plymouth Theme]\n"
        "Name=Portable OS\n"
        "Description=Белый текст на чёрном: пароль, компьютер, восстановление\n"
        "ModuleName=script\n"
        "\n"
        "[script]\n"
        f"ImageDir={theme_dir}\n"
        f"ScriptFile={theme_dir}/{PLYMOUTH_THEME_NAME}.script\n"
    )


def script() -> str:
    """Сам экран для плагина `script`: чёрный фон и белый текст по центру.

    Пишется здесь, а не в семействе, потому что облик у носителя один: то
    же, что `two-step` получает ключами, `script` получает этим кодом.

    Реализованы ровно те четыре события, которыми носитель разговаривает с
    человеком, -- сообщение, запрос пароля, вопрос и возврат к обычному
    экрану. Больше ничего: ни логотипа, ни полосы, ни анимации. Экран
    показывается, когда спрашивают пароль и когда что-то пошло не так, и в
    обоих случаях внимание должно быть на тексте.

    Пустой текст `Image.Text("")` даёт ничто, а не пустую картинку, и
    `SetImage` на нём роняет спрайт в неопределённое состояние, поэтому
    снятие сделано прозрачностью: спрайт остаётся, его просто не видно.
    """
    return (
        "# generated by portable-os-admin\n"
        "# Экран, которым носитель разговаривает с человеком до загрузки.\n"
        "Window.SetBackgroundTopColor(0, 0, 0);\n"
        "Window.SetBackgroundBottomColor(0, 0, 0);\n"
        "\n"
        "message = Sprite();\n"
        "prompt = Sprite();\n"
        "entry = Sprite();\n"
        "\n"
        "fun white(text) {\n"
        "    return Image.Text(text, 1, 1, 1);\n"
        "}\n"
        "\n"
        "# По центру по горизонтали, на заданной высоте.\n"
        "fun show(sprite, text, y) {\n"
        "    image = white(text);\n"
        "    sprite.SetImage(image);\n"
        "    sprite.SetX(Window.GetWidth() / 2 - image.GetWidth() / 2);\n"
        "    sprite.SetY(y);\n"
        "    sprite.SetOpacity(1);\n"
        "}\n"
        "\n"
        "fun hide(sprite) {\n"
        "    sprite.SetOpacity(0);\n"
        "}\n"
        "\n"
        "# Сообщение -- в верхней трети: под ним встаёт запрос пароля.\n"
        "fun message_callback(text) {\n"
        "    show(message, text, Window.GetHeight() / 4);\n"
        "}\n"
        "Plymouth.SetDisplayMessageFunction(message_callback);\n"
        "\n"
        "fun hide_message_callback(text) {\n"
        "    hide(message);\n"
        "}\n"
        "Plymouth.SetHideMessageFunction(hide_message_callback);\n"
        "\n"
        "# Пароль: приглашение и звёздочки по числу набранных знаков.\n"
        "fun password_callback(text, bullets) {\n"
        "    show(prompt, text, Window.GetHeight() / 2);\n"
        "    stars = \"\";\n"
        "    i = 0;\n"
        "    while (i < bullets) {\n"
        "        stars += \"*\";\n"
        "        i++;\n"
        "    }\n"
        "    show(entry, stars, Window.GetHeight() / 2 + 40);\n"
        "}\n"
        "Plymouth.SetDisplayPasswordFunction(password_callback);\n"
        "\n"
        "# Вопрос: ввод виден. Им спрашивают согласие занять слот и код\n"
        "# восстановления -- код переписывают с бумажки, и человек должен\n"
        "# видеть, что набрал.\n"
        "fun question_callback(text, answer) {\n"
        "    show(prompt, text, Window.GetHeight() / 2);\n"
        "    show(entry, answer, Window.GetHeight() / 2 + 40);\n"
        "}\n"
        "Plymouth.SetDisplayQuestionFunction(question_callback);\n"
        "\n"
        "# Обычный экран: вопроса больше нет, сообщение остаётся.\n"
        "fun normal_callback() {\n"
        "    hide(prompt);\n"
        "    hide(entry);\n"
        "}\n"
        "Plymouth.SetDisplayNormalFunction(normal_callback);\n"
    )
