"""Носитель как сущность, а не как «блочное устройство с нашей разметкой».

Зачем это здесь. Решение 16.09.2026: у решения будет два вида носителя --
обычная флешка (менее защищённый путь) и токен с управляемыми правами разделов
(более защищённый). Экземпляра токена пока нет, работа по нему начнётся, когда
он появится; но архитектура обязана оставить ему место **сейчас**, иначе через
месяц окажется, что знание о носителе размазано по десятку файлов и заменить в
нём нечего.

Разведка 16.09.2026 показала, где это знание живёт сегодня: `install/installer`
(рождение ключей), `install/luks` (слоты), `install/backends/text/tables`
(crypttab), `admin/service_volumes` (открытие томов на машине администратора),
`admin/media_lookup` и `admin/media_detect` (опознание), `install/integrity` и
экран целостности (опись загрузчика). Ни одно из этих мест не спрашивает
«а какой у нас носитель» -- каждое просто знает про флешку.

Модуль называет **три решения**, и ровно они у токена другие:

1. **Чем открывается том.** У флешки -- парольная фраза пользователя, а
   служебные тома открываются файлом ключа на зашифрованном корне. У токена
   ключ живёт в чипе и наружу не выходит: скопированный образ не открыть даже
   с фразой.
2. **Чем защищена загрузочная часть.** У флешки -- опись `/boot` и ESP,
   подписанная ключом администратора: это **обнаружение** подмены, а не запрет,
   и так прямо сказано в README. У токена -- раздел «только чтение», права
   которого меняет сам контроллер по PIN: это **запрет**.
3. **Чем носитель опознаётся без пароля.** У флешки -- файл `media_id.txt` на
   ESP и UUID томов LUKS. У токена к этому добавляется серийный номер чипа,
   который нельзя переписать, скопировав раздел.

LIVE-2.0 (01.10.2026) добавила ещё три решения, которые у токена другие, -- все
про то, как носитель доказывает серверу доступа, что он это он
(`docs/LIVE-2.0.md`, раздел «Сервер доступа»):

4. **Где ключ носителя и каким алгоритмом он подписывает.** У флешки --
   файл Ed25519 в хранилище; у токена -- неизвлекаемый ключ в чипе через
   PKCS#11, алгоритм (P-256 или ГОСТ) выберется, когда появится экземпляр.
5. **Чем ловится клон.** У флешки ключ можно скопировать вместе с хранилищем,
   поэтому клон ловит сдвигающееся звено последовательности на сервере. У
   токена ключ не копируется -- звено не нужно.
6. **Нужен ли TOTP.** У флешки -- да: он закрывает кражу самой флешки вместе
   с подсмотренной фразой. У токена PIN и чип уже дают два фактора, TOTP --
   по настройке администратора.

Больше модуль ничего не делает и не должен: это граница, а не слой поверх
установщика. Поведение флешки описано здесь честно, как оно есть сегодня, --
чтобы при появлении токена было видно, что именно меняется, и не пришлось
выяснять это чтением десяти файлов.
"""
from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Protocol

from .backends.constants import SERVICE_KEY_PATH


class VolumeKey(Enum):
    """Чем открывается системный том носителя."""

    #: Парольная фраза пользователя; служебные тома -- файлом ключа на корне.
    PASSPHRASE = "passphrase"
    #: Ключ вырабатывается внутри устройства и наружу не выходит.
    DEVICE_CHIP = "device-chip"


class BootProtection(Enum):
    """Чем защищена незашифрованная загрузочная часть."""

    #: Опись путей и хешей, подписанная ключом администратора. Обнаруживает
    #: подмену после факта -- initramfs успевает получить парольную фразу.
    SIGNED_MANIFEST = "signed-manifest"
    #: Раздел, который устройство отдаёт только для чтения; права меняются
    #: аутентификацией в самом устройстве, а не на хосте.
    DEVICE_READ_ONLY = "device-read-only"


class Identification(Enum):
    """Чем носитель опознаётся администратором без парольной фразы."""

    #: `poa/media_id.txt` на ESP плюс UUID томов LUKS.
    BOOT_METADATA = "boot-metadata"
    #: Неперезаписываемый признак самого устройства (серийный номер чипа).
    DEVICE_IDENTITY = "device-identity"


class DeviceKey(Enum):
    """Где живёт ключ, которым носитель подписывает запросы к серверу доступа."""

    #: Файл закрытого ключа в хранилище носителя (под LUKS).
    FILE = "file"
    #: Неизвлекаемый ключ в чипе; подпись делает сам чип через PKCS#11.
    PKCS11 = "pkcs11"


class CloneProtection(Enum):
    """Чем сервер отличает носитель от его копии."""

    #: Сдвигающееся звено: сертификат выдаётся только после того, как носитель
    #: подтвердил запись нового звена; предъявление старого -- клон.
    RATCHET = "ratchet"
    #: Ключ не покидает чипа, копия без устройства подписать ничего не может.
    DEVICE_KEY = "device-key"


class DeviceSigner(Protocol):
    """Подписант носителя: то, что доказывает серверу доступа «это я».

    Граница нарочно узкая -- подпись байтов и открытый ключ. Флешка реализует
    её файлом ключа, токен -- вызовом PKCS#11; остальной клиент сеанса не знает,
    какой у него носитель. Реализации появятся в клиенте сеанса (этап Э8);
    здесь только договор.
    """

    #: Имя алгоритма для поля `alg` протокола v3: "ed25519", позже "p256"
    #: или "gost2012-256". Сервер проверяет подпись тем алгоритмом, который
    #: записан за носителем при регистрации, а не тем, что пришёл в запросе.
    alg: str

    def public_key(self) -> bytes:
        """Открытый ключ в том виде, в каком его регистрирует администратор."""
        ...

    def sign(self, data: bytes) -> bytes:
        """Подпись `data`; для токена -- внутри чипа."""
        ...


@dataclass(frozen=True)
class MediumProfile:
    """Вид носителя: три решения и их следствия для программы."""

    name: str
    title: str
    volume_key: VolumeKey
    boot_protection: BootProtection
    identification: Identification
    #: Где на носителе лежит файл ключа служебных томов. Пусто, если ключ
    #: живёт в устройстве и файла нет вовсе.
    service_key_path: str = ""
    #: Где ключ носителя для протокола сервера доступа.
    device_key: DeviceKey = DeviceKey.FILE
    #: Алгоритм подписи носителя. Пусто -- ещё не выбран.
    signature_alg: str = "ed25519"
    #: Чем сервер ловит копию носителя.
    clone_protection: CloneProtection = CloneProtection.RATCHET
    #: Требовать ли TOTP по умолчанию (администратор может переопределить).
    totp_by_default: bool = True

    @property
    def key_leaves_the_medium(self) -> bool:
        """Можно ли открыть данные, унеся копию образа.

        У флешки -- да, если известна фраза: ключ выводится из неё. Это и есть
        граница, названная в README честно. У токена -- нет: без устройства
        копия бесполезна.
        """
        return self.volume_key is VolumeKey.PASSPHRASE

    @property
    def boot_tampering_is_prevented(self) -> bool:
        """Запрещена ли подмена загрузчика, а не только замечена."""
        return self.boot_protection is BootProtection.DEVICE_READ_ONLY

    def describe(self) -> str:
        """Одна строка для интерфейса и журналов."""
        if self.boot_tampering_is_prevented:
            boot = "загрузочная часть защищена устройством"
        else:
            boot = "подмена загрузчика обнаруживается описью, но не запрещается"
        if self.key_leaves_the_medium:
            key = "ключ тома выводится из парольной фразы"
        else:
            key = "ключ тома не покидает устройства"
        return f"{self.title}: {key}; {boot}"


#: Обычная флешка -- то, что программа умеет сегодня.
FLASH = MediumProfile(
    name="flash",
    title="Обычная флешка",
    volume_key=VolumeKey.PASSPHRASE,
    boot_protection=BootProtection.SIGNED_MANIFEST,
    identification=Identification.BOOT_METADATA,
    service_key_path=SERVICE_KEY_PATH,
)

#: Токен -- **проект**, а не поддерживаемый вид. Описан сейчас, чтобы клиент
#: сеанса, протокол и разметка с первого дня спрашивали профиль, а не знали
#: про флешку (требование архитектуры, LIVE-2.0). В `PROFILES` его нет и не
#: будет, пока экземпляр не проверен живым прогоном: заранее объявленный вид
#: выглядел бы как поддержка, которой нет. Образец для расчётов -- Рутокен
#: ЭЦП 2.0 Flash: раздел «только чтение» под загрузку, ключи в чипе.
TOKEN_DRAFT = MediumProfile(
    name="token",
    title="Токен с флеш-памятью (проект)",
    volume_key=VolumeKey.DEVICE_CHIP,
    boot_protection=BootProtection.DEVICE_READ_ONLY,
    identification=Identification.DEVICE_IDENTITY,
    service_key_path="",
    device_key=DeviceKey.PKCS11,
    # Рутокен не умеет Ed25519; P-256 или ГОСТ -- решение до появления
    # экземпляра не принимается (01.10.2026).
    signature_alg="",
    clone_protection=CloneProtection.DEVICE_KEY,
    totp_by_default=False,
)

#: Виды носителей, известные программе. Токен встанет сюда вторым, когда
#: появится экземпляр: до тех пор выдумывать его поведение нельзя -- не
#: проверено ни одной строчкой.
PROFILES: "dict[str, MediumProfile]" = {FLASH.name: FLASH}

#: Вид по умолчанию. Отдельным именем, а не `PROFILES["flash"]` по месту:
#: когда видов станет два, выбор появится в одном месте, а не в десяти.
DEFAULT = FLASH


def profile(name: str = "") -> MediumProfile:
    """Вид носителя по имени; без имени -- вид по умолчанию.

    Неизвестное имя -- не исключение, а возврат к умолчанию: конфигурация,
    записанная будущей версией с токеном, не должна ронять сегодняшнюю
    программу, она должна собрать флешку и сказать об этом.
    """
    return PROFILES.get(name or DEFAULT.name, DEFAULT)
