def describe(media: str, code: str, params: dict | None = None) -> str:
    """`ID_носителя: расшифровка` -- запись для журнала администратора."""
    level, text = EVENTS.get(code, ("?", f"неизвестный код {code}"))
    tail = ", ".join(f"{k}={v}" for k, v in sorted((params or {}).items()))
    return f"{media}: [{level}] {text}" + (f" ({tail})" if tail else "")
