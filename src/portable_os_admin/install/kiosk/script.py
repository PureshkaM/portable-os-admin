"""Скрипт, применяющий список разрешённых приложений на целевой системе.

Каркас общий, а всё, что зависит от среды, приходит одним фрагментом от неё
самой -- см. environments/base.py.
"""
from __future__ import annotations

from ...config.schema import InstallConfig
from .common import OVERRIDE_DIR, desktop_of
from .environments import base as environments

# ----------------------------------------------------------------------
# The whitelist, applied inside the target
# ----------------------------------------------------------------------
def apply_script(config: InstallConfig, image=None) -> str:
    """Shell script that hides every launcher outside the whitelist.

    It runs in the chroot rather than being a set of files written from here
    because the set of installed desktop entries is only known once the
    packages are in: a package can install launchers nobody asked for, and
    those are exactly the ones that must disappear.

    Hiding is done with an override file in /usr/local/share/applications, not
    by deleting anything: XDG_DATA_DIRS searches /usr/local/share first, so a
    same-named entry wins while the packaged file stays intact and a later
    `kiosk off` is a matter of removing one directory.

    The override is a **copy of the original with NoDisplay=true added**, not a
    stub. Writing a stub with Hidden=true and no Exec broke the session
    outright, and only a real boot showed it: marco and mate-panel (and, at the
    time, caja -- since removed from the package set) are not menu entries but
    components of the desktop itself, and mate-session reads their .desktop
    files to start them. With no Exec it started none of
    them, so the medium booted to a black screen -- autologin fine, X running,
    and nothing inside. Hidden=true means "this entry has been deleted";
    NoDisplay=true means "it exists, just keep it out of the menu", which is
    what was wanted all along.

    Список разрешённого не задаётся, а **выводится из пакетов** администратора,
    и это решение 02.09.2026, меняющее смысл настройки.

    Наше дело -- собрать минимальную систему, в которой пользователю не
    доступно ни одного приложения; администратор ставит поверх неё то, с чем
    пользователь работает. Значит «разрешённые приложения» -- не отдельный
    список, а следствие выбора пакетов: что поставлено, то и доступно.

    Раньше здесь стоял список имён, введённый руками, и он давал ошибку,
    которую нечем поймать: прогон 02.09.2026 разрешил `atril`, пакет с ним не
    поставил -- и меню оказалось пустым, а узнал бы об этом администратор
    только от пользователя. Имя пакета и имя его desktop-записи совпадают
    далеко не всегда, и один пакет нередко ставит несколько запускателей.

    Поэтому список собирает сама целевая система: спрашивает менеджер пакетов,
    какие `.desktop` принесли пакеты администратора, и разрешает ровно их.
    Снятое администратором (`kiosk.hidden_launchers`) вычитается -- один пакет
    вроде LibreOffice приносит шесть запускателей, и лишние надо уметь убрать.

    Имена пакетов и снятых запускателей вписаны в текст скрипта, а не переданы
    аргументами: то, что никогда не попадает в командную строку, нельзя
    закавычить неправильно.
    """
    kiosk = config.kiosk
    packages = " ".join(sorted(set(config.packages)))
    hidden = " ".join(sorted(set(getattr(kiosk, "hidden_launchers", ()))))
    # Импорт локальный: бэкенды сами читают этот модуль, и на уровне файла
    # получилось бы кольцо.
    from ..backends import get_backend

    files_command = " ".join(get_backend(config.target_os).PACKAGE_FILES_COMMAND)
    firejail_opts = kiosk.firejail_options.strip()
    use_firejail = "1" if kiosk.firejail else ""
    desktop = desktop_of(config)
    environment = environments.for_config(config, image)
    # Ярлык, который виден и не запускается, хуже отсутствующего -- отвечает
    # на это сама среда, потому что причина у каждой своя.
    shortcuts = "1" if environment.desktop_shortcuts_work(config) else ""
    # Ярлык -- ссылка или копия: у сред разные представления о том, какому
    # `.desktop` можно доверять. См. `desktop_shortcuts_are_links`.
    shortcut_links = "1" if environment.desktop_shortcuts_are_links else ""
    return f"""#!/bin/sh
# generated by portable-os-admin
# Применяет список разрешённых приложений режима киоска.
set -eu

POA_PACKAGES="{packages}"
POA_HIDDEN="{hidden}"
PKG_FILES="{files_command}"
DESKTOP="{desktop}"
USE_FIREJAIL="{use_firejail}"
FIREJAIL_OPTS="{firejail_opts}"
DESKTOP_SHORTCUTS="{shortcuts}"
DESKTOP_SHORTCUT_LINKS="{shortcut_links}"
OVERRIDE_DIR=/{OVERRIDE_DIR}

mkdir -p "$OVERRIDE_DIR"

is_hidden() {{
    for h in $POA_HIDDEN; do
        [ "$h" = "$1" ] && return 0
    done
    return 1
}}

# Что поставил администратор, то пользователю и доступно.
#
# Спрашиваем менеджер пакетов, а не гадаем по именам: имя пакета и имя его
# desktop-записи совпадают далеко не всегда (`libreoffice-writer` ставит
# `libreoffice-startcenter` в придачу), а пакет без единого запускателя --
# обычное дело, это библиотека или шрифт.
ALLOWED=""
found_packages=0
for pkg in $POA_PACKAGES; do
    entries=$($PKG_FILES "$pkg" 2>/dev/null \
        | sed -n 's|^/usr/share/applications/\\([^/]*\\)\\.desktop$|\\1|p')
    [ -n "$entries" ] && found_packages=$((found_packages + 1))
    for name in $entries; do
        if is_hidden "$name"; then
            echo "poa-kiosk: запускатель '$name' из пакета '$pkg' скрыт по решению администратора"
            continue
        fi
        ALLOWED="$ALLOWED $name"
    done
done

if [ -z "$ALLOWED" ]; then
    # Не ошибка установки, но носитель, на котором пользователю нечего
    # открыть. Сказать об этом надо здесь: снаружи это выглядит как пустое
    # меню, и разбираться придётся уже после выдачи носителя.
    echo "poa-kiosk: ВНИМАНИЕ: ни один из выбранных пакетов не принёс" \
         "ни одного приложения, пользователю нечего будет запустить" >&2
else
    echo "poa-kiosk: пользователю доступны приложения:$ALLOWED"
fi

is_allowed() {{
    for a in $ALLOWED; do
        [ "$a" = "$1" ] && return 0
    done
    return 1
}}

# Скрыть всё, что не разрешено явно.
hidden=0
for f in /usr/share/applications/*.desktop; do
    [ -e "$f" ] || continue
    name=${{f##*/}}
    name=${{name%.desktop}}
    if is_allowed "$name"; then
        continue
    fi
    # Копия исходной записи плюс NoDisplay=true — а не подмена её пустышкой.
    #
    # Раньше здесь создавалась запись с Hidden=true и без Exec, и это ломало
    # сессию целиком. marco и mate-panel — не «приложения из меню», а
    # компоненты самой среды: оконный менеджер и панель. mate-session читает
    # их .desktop, чтобы запустить их, не находит Exec и не поднимает ни
    # одного. Тогда в этом ряду стоял и caja; из набора пакетов он с тех пор
    # убран, но урок относится к любому компоненту среды. Носитель загружался в чёрный экран:
    # автологин проходил, X работал, а внутри не было ни окон, ни панели.
    #
    # Hidden=true по спецификации значит «записи больше нет», то есть её
    # удалили. NoDisplay=true значит «есть, но не показывать в меню» — ровно
    # то, что нужно: запись остаётся исправной для всего, что запускает её
    # само.
    awk '
        /^\\[Desktop Entry\\]/ {{ print; print "NoDisplay=true"; next }}
        /^NoDisplay[[:space:]]*=/ {{ next }}
        /^Hidden[[:space:]]*=/ {{ next }}
        {{ print }}
    ' "$f" > "$OVERRIDE_DIR/$name.desktop"
    hidden=$((hidden + 1))
done
echo "poa-kiosk: скрыто записей приложений: $hidden"

# Снятый запускатель, которого не оказалось ни в одном пакете, -- след
# устаревшей конфигурации: администратор снял галочку, а пакет с тех пор
# сменил состав. Молчать об этом нельзя: выглядит это как исправная настройка.
for h in $POA_HIDDEN; do
    if [ ! -f "/usr/share/applications/$h.desktop" ]; then
        echo "poa-kiosk: ВНИМАНИЕ: скрыт запускатель '$h', но такого в системе нет" >&2
    fi
done

# Ярлыки разрешённых приложений на Рабочем столе.
#
# Так же, как в штатном киоске РЕД ОС: «ярлыки таких приложений находятся на
# Рабочем столе». Это не украшение, а единственный надёжный способ запустить
# приложение в запертой среде — панель заблокирована, а меню может быть
# недоступно. Первый собранный носитель загрузился именно в такое состояние:
# приложения установлены и разрешены, а открыть их нечем.
#
# Кладутся и в /etc/skel (для учётных записей, которые создадут позже), и в
# домашний каталог уже существующего пользователя, потому что порядок шагов
# установки на это не влияет.
placed=0
if [ -z "$DESKTOP_SHORTCUTS" ]; then
    echo "poa-kiosk: ярлыки на рабочем столе не кладутся: запрет run_desktop_files" \
         "не даст их запустить, запуск идёт из меню" >&2
fi
for home in /etc/skel /home/*; do
    [ -n "$DESKTOP_SHORTCUTS" ] || break
    [ -d "$home" ] || continue
    desktop_dir="$home/Desktop"
    mkdir -p "$desktop_dir" || continue
    for a in $ALLOWED; do
        src="/usr/share/applications/$a.desktop"
        [ -f "$src" ] || continue
        rm -f "$desktop_dir/$a.desktop"
        if [ -n "$DESKTOP_SHORTCUT_LINKS" ]; then
            # KDE доверяет записи по её каноническому пути: ссылка на
            # /usr/share/applications проходит проверку в первой же ветви
            # `isAuthorizedDesktopFile`, а копия в домашнем каталоге -- нет.
            # Прогон 07.09.2026: копия спрашивала «This will start the
            # program…» и после согласия отвечала «You are not authorized to
            # execute this file», причём запрет `shell_access` тут ни при чём
            # -- его сняли на носителе и загрузились снова, отказ остался.
            ln -s "$src" "$desktop_dir/$a.desktop" 2>/dev/null || continue
        else
            cp "$src" "$desktop_dir/$a.desktop" 2>/dev/null || continue
            # Caja запускает ярлык только если он исполняемый и помечен
            # доверенным.
            chmod 0755 "$desktop_dir/$a.desktop" 2>/dev/null || true
        fi
        placed=$((placed + 1))
    done
    # Владелец: домашний каталог пользователя должен остаться его.
    owner=${{home##*/}}
    if [ "$home" != "/etc/skel" ]; then
        chown -R "$owner:$owner" "$desktop_dir" 2>/dev/null || true
    fi
done
echo "poa-kiosk: ярлыков на рабочем столе размещено: $placed"

# Песочница: разрешённые приложения перезапускаются через firejail.
# Только если пакет есть — в образе Debian DVD его нет, и тогда это не отказ
# установки, а работа без дополнительного слоя, о чём сказано в журнале.
if [ -n "$USE_FIREJAIL" ]; then
    if command -v firejail >/dev/null 2>&1; then
        for a in $ALLOWED; do
            src="/usr/share/applications/$a.desktop"
            [ -f "$src" ] || continue
            sed "s|^Exec=|Exec=firejail $FIREJAIL_OPTS |" "$src" > "$OVERRIDE_DIR/$a.desktop"
        done
        echo "poa-kiosk: разрешённые приложения запускаются в песочнице firejail"
    else
        echo "poa-kiosk: firejail не установлен, песочница не применена" >&2
    fi
fi

{environment.apply_fragment(config)}
"""


