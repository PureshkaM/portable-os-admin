def hardening_fstab_rows() -> list[tuple[str, str, str, str, str, str]]:
    """fstab rows that take execution away from everything the user can write.

    /home is bind-mounted onto itself purely to carry mount options: it lives
    on the root filesystem, which must stay executable, so the options cannot
    be set on the root mount. /tmp and /var/tmp become tmpfs, which also means
    nothing a session writes there survives a reboot.

    This is the layer that does not depend on any desktop setting being
    honoured -- it is the kernel refusing execve, and it is why a file arriving
    on the exchange volume cannot be run no matter what the user clicks.
    """
    return [
        ("/home", "/home", "none", f"bind,{HARDENED_OPTS}", "0", "0"),
        ("tmpfs", "/tmp", "tmpfs", f"{HARDENED_OPTS},mode=1777", "0", "0"),
        ("tmpfs", "/var/tmp", "tmpfs", f"{HARDENED_OPTS},mode=1777", "0", "0"),
    ]

#: Службы, которых в киоске быть не должно, даже если дистрибутив включает их
#: сам. Маскируются, а не выключаются: выключенную службу поднимет обратно
#: первое же обновление пакета, замаскированную -- нет.
#:
#: Список закрыт по одному признаку: служба слушает сеть или отдаёт наружу
#: сведения о машине, а киоску это не нужно ни для чего. На собранном носителе
#: РЕД ОС в журнале видно работающими sshd и avahi -- ни один из них не был
#: заказан, оба пришли с дистрибутивом.
#:
#: Замер, ради которого это не «на всякий случай»: носитель попадает в чужую
#: сеть, где каждая слушающая служба -- это и поверхность атаки, и объявление
#: о себе. Удалённый доступ к самому носителю не предусмотрен по замыслу:
#: администратор работает с ним через собственный интерфейс программы.
UNWANTED_SERVICES = (
    "sshd.service",
    "ssh.service",
    "avahi-daemon.service",
    "avahi-daemon.socket",
    "smbd.service",
    "nmbd.service",
    "cups.service",
    "cups.socket",
    # Не служба, а цель, и здесь она по той же причине: своп машины-хозяина
    # означал бы страницы памяти пользователя, записанные открытым текстом на
    # чужой диск. Своего свопа у носителя нет, поэтому цель не нужна вовсе.
    "swap.target",
)

#: Параметры ядра, которыми держится обособленность и закрывается DMA.
#:
#: `iommu=force` и семейные `intel_iommu=on` / `amd_iommu=on` -- против чтения
#: памяти через Thunderbolt и PCIe: без них мастер-ключ LUKS достаётся из
#: оперативной памяти устройством, воткнутым в разъём.
#:
#: `noresume` -- против чужого образа гибернации: без него systemd находит на
#: диске машины-хозяина чужой resume-образ и пытается его возобновить, то есть
#: поднять чужую систему вместо нашей.
#:
#: `nohibernate` -- против своей: гибернация пишет всю память на диск, а для
#: переносного носителя это вынос данных целиком.
HARDENING_KERNEL_PARAMETERS = (
    # Включить IOMMU там, где он есть. Намеренно без `iommu=force`: тот
    # требует IOMMU безусловно и на части машин мешает загрузке, а носитель
    # обязан грузиться на железе, которого никто не видел. Защита, из-за
    # которой система не стартует, защищает только от пользователя.
    "intel_iommu=on",
    "amd_iommu=on",
    # Не отдавать устройствам прямой доступ в обход трансляции адресов.
    "iommu.passthrough=0",
    # Закрыть DMA ещё до того, как ядро возьмёт управление у прошивки, — окно,
    # в котором IOMMU настроить некому.
    "efi=disable_early_pci_dma",
    "noresume",
    "nohibernate",
)

#: Где правилу НЕ место. Константа осталась ради теста, который следит, что
#: файла по этому пути на носителе нет: положенное в /etc правило срабатывает
#: на coldplug и отключает загрузочный накопитель (см. `usb_lockdown_unit`).
UDEV_RULES_PATH = "etc/udev/rules.d/99-poa-kiosk-storage.rules"


def udev_storage_rules(config: InstallConfig) -> str:
    """Запрет на чужие USB-накопители, если администратор их не разрешил.

    Выключенного автомонтирования мало: оно закрывает удобный путь, а не
    возможность. Диск, подключённый к работающей системе, всё равно появляется
    как устройство, и всё, что умеет читать блочные устройства, его увидит.

    Закрывается там, где устройство появляется: USB-накопитель не
    авторизуется, поэтому ядро не создаёт для него ни узла, ни разделов.

    **Правило не кладётся в систему статически, и это главное здесь.** Первая
    версия писала его в `/etc/udev/rules.d` с рассуждением «носитель, с
    которого загрузились, уже работает и под правило не попадает». Оно
    неверно: при переходе из initramfs systemd выполняет coldplug --
    `udevadm trigger --action=add` по всем уже существующим устройствам, -- и
    `ACTION=="add"` приходит в том числе для загрузочного носителя. Носитель
    деавторизовывал сам себя: `Synchronizing SCSI cache`, отказ ввода-вывода
    и корень, перемонтированный только для чтения. Найдено прогоном
    28.08.2026, и тестами такое не ловится в принципе.

    Поэтому запрет включается службой после того, как система поднялась:
    правило пишется в `/run/udev/rules.d`, где переживает только текущую
    загрузку, и вступает в силу для того, что подключат дальше. Момент выбран
    так, что coldplug к этому времени завершён и носитель авторизован.

    Разрешив съёмные носители, администратор получает обычное поведение: ни
    файла, ни службы тогда не появляется вовсе -- а не пустое правило, которое
    `udevadm` показывает, но которое ничего не делает.
    """
    if config.kiosk.allow_removable_media:
        return ""
    return (
        "# generated by portable-os-admin\n"
        "# Съёмные носители пользователю запрещены: накопитель, подключённый\n"
        "# после загрузки, не авторизуется, и устройство для него не создаётся.\n"
        "#\n"
        "# Файл кладётся в /run службой poa-usb-lockdown.service уже после\n"
        "# запуска системы. В /etc ему не место: coldplug при переходе из\n"
        "# initramfs шлёт ACTION=add и для загрузочного носителя, и тот\n"
        "# отключает сам себя.\n"
        'ACTION=="add", SUBSYSTEM=="usb", ENV{DEVTYPE}=="usb_device", '
        'ATTR{bInterfaceClass}=="08", ATTR{authorized}="0"\n'
        "# То же для устройств, объявляющих класс на уровне интерфейса.\n"
        'ACTION=="add", SUBSYSTEM=="usb", ATTRS{bInterfaceClass}=="08", '
        'TEST=="../authorized", ATTR{../authorized}="0"\n'
    )


#: Правило, убирающее служебные разделы носителя из глаз рабочего стола.
#:
#: В отличие от запрета USB выше, это правило кладётся статически в /etc, и
#: coldplug ему не помеха: оно ничего не деавторизует и не отключает, а лишь
